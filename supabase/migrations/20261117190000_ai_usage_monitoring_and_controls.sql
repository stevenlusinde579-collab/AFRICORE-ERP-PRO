-- Annual per-school Gemini AI usage limits and Super Admin controls.
-- One annual upload batch is represented by an exam_id; each batch may contain
-- up to exams_per_upload_limit distinct exam_paper_id records.
-- Defaults: 10 batches per school per Tanzania calendar year, 20 papers per batch.

create table if not exists public.gemini_ai_usage_policies (
    school_id bigint primary key references public.schools(id) on delete cascade,
    is_enabled boolean not null default true,
    annual_upload_limit integer not null default 10 check (annual_upload_limit between 0 and 10000),
    exams_per_upload_limit integer not null default 20 check (exams_per_upload_limit between 0 and 1000),
    admin_note text,
    updated_by uuid references public.profiles(id) on delete set null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.gemini_ai_usage_reservations (
    id bigint generated by default as identity primary key,
    school_id bigint not null references public.schools(id) on delete cascade,
    usage_year integer not null,
    exam_id bigint not null,
    exam_paper_id bigint not null,
    actor_user_id uuid references public.profiles(id) on delete set null,
    status text not null default 'reserved'
        check (status in ('reserved','completed','failed','historical')),
    reserved_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (school_id, usage_year, exam_paper_id)
);

create index if not exists gemini_ai_usage_reservations_school_year_idx
    on public.gemini_ai_usage_reservations (school_id, usage_year, reserved_at desc);
create index if not exists gemini_ai_usage_reservations_batch_idx
    on public.gemini_ai_usage_reservations (school_id, usage_year, exam_id);

create table if not exists public.gemini_ai_usage_policy_audit (
    id bigint generated by default as identity primary key,
    school_id bigint not null references public.schools(id) on delete cascade,
    actor_user_id uuid references public.profiles(id) on delete set null,
    action text not null,
    old_values jsonb,
    new_values jsonb,
    created_at timestamptz not null default now()
);

create index if not exists gemini_ai_usage_policy_audit_school_created_idx
    on public.gemini_ai_usage_policy_audit (school_id, created_at desc);

alter table public.gemini_ai_usage_policies enable row level security;
alter table public.gemini_ai_usage_reservations enable row level security;
alter table public.gemini_ai_usage_policy_audit enable row level security;

revoke all on public.gemini_ai_usage_policies from anon, authenticated;
revoke all on public.gemini_ai_usage_reservations from anon, authenticated;
revoke all on public.gemini_ai_usage_policy_audit from anon, authenticated;

grant all on public.gemini_ai_usage_policies to service_role;
grant all on public.gemini_ai_usage_reservations to service_role;
grant all on public.gemini_ai_usage_policy_audit to service_role;
grant usage, select on sequence public.gemini_ai_usage_reservations_id_seq to service_role;
grant usage, select on sequence public.gemini_ai_usage_policy_audit_id_seq to service_role;

insert into public.gemini_ai_usage_policies (school_id)
select id from public.schools
on conflict (school_id) do nothing;

-- Preserve the usage already recorded for the current and previous years so
-- rollout does not reset a school's annual allowance.
insert into public.gemini_ai_usage_reservations
    (school_id, usage_year, exam_id, exam_paper_id, status, reserved_at)
select distinct on (school_id, extract(year from created_at at time zone 'Africa/Dar_es_Salaam')::integer, exam_paper_id)
    school_id,
    extract(year from created_at at time zone 'Africa/Dar_es_Salaam')::integer,
    exam_id,
    exam_paper_id,
    'historical',
    min(created_at) over (partition by school_id, extract(year from created_at at time zone 'Africa/Dar_es_Salaam')::integer, exam_paper_id)
from public.gemini_usage_logs
where exam_id is not null and exam_paper_id is not null
order by school_id, extract(year from created_at at time zone 'Africa/Dar_es_Salaam')::integer, exam_paper_id, created_at;

create or replace function public.reserve_gemini_ai_analysis_slot(
    p_school_id bigint,
    p_exam_id bigint,
    p_exam_paper_id bigint,
    p_actor_user_id uuid default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_year integer := extract(year from (now() at time zone 'Africa/Dar_es_Salaam'))::integer;
    v_policy public.gemini_ai_usage_policies%rowtype;
    v_existing public.gemini_ai_usage_reservations%rowtype;
    v_uploads integer := 0;
    v_papers_in_batch integer := 0;
begin
    if p_school_id is null or p_school_id <= 0 or p_exam_id is null or p_exam_id <= 0
       or p_exam_paper_id is null or p_exam_paper_id <= 0 then
        return jsonb_build_object('allowed', false, 'code', 'INVALID_USAGE_CONTEXT');
    end if;

    insert into public.gemini_ai_usage_policies (school_id)
    values (p_school_id)
    on conflict (school_id) do nothing;

    select * into v_policy
    from public.gemini_ai_usage_policies
    where school_id = p_school_id
    for update;

    if not found then
        return jsonb_build_object('allowed', false, 'code', 'POLICY_NOT_FOUND');
    end if;

    select * into v_existing
    from public.gemini_ai_usage_reservations
    where school_id = p_school_id
      and usage_year = v_year
      and exam_paper_id = p_exam_paper_id;

    -- Ensure the paper and exam really belong to the school passed by the backend.
    if not exists (
        select 1
        from public.exam_papers ep
        join public.exams e on e.id = ep.exam_id
        where ep.id = p_exam_paper_id
          and ep.exam_id = p_exam_id
          and e.school_id = p_school_id
    ) then
        return jsonb_build_object(
            'allowed', false,
            'code', 'USAGE_CONTEXT_MISMATCH',
            'message', 'The examination paper does not belong to this school and examination.'
        );
    end if;

    if not v_policy.is_enabled then
        return jsonb_build_object(
            'allowed', false,
            'code', 'AI_USAGE_DISABLED',
            'message', 'AI Analysis has been disabled for this school by the system administrator.',
            'usage_year', v_year,
            'annual_upload_limit', v_policy.annual_upload_limit,
            'exams_per_upload_limit', v_policy.exams_per_upload_limit
        );
    end if;

    if found then
        if v_existing.exam_id <> p_exam_id then
            return jsonb_build_object('allowed', false, 'code', 'USAGE_CONTEXT_MISMATCH');
        end if;

        select count(distinct exam_id)::integer into v_uploads
        from public.gemini_ai_usage_reservations
        where school_id = p_school_id and usage_year = v_year;

        select count(*)::integer into v_papers_in_batch
        from public.gemini_ai_usage_reservations
        where school_id = p_school_id and usage_year = v_year and exam_id = p_exam_id;

        return jsonb_build_object(
            'allowed', true,
            'already_reserved', true,
            'usage_year', v_year,
            'uploads_used', v_uploads,
            'upload_limit', v_policy.annual_upload_limit,
            'papers_in_upload', v_papers_in_batch,
            'papers_per_upload_limit', v_policy.exams_per_upload_limit
        );
    end if;

    select count(distinct exam_id)::integer into v_uploads
    from public.gemini_ai_usage_reservations
    where school_id = p_school_id and usage_year = v_year;

    select count(*)::integer into v_papers_in_batch
    from public.gemini_ai_usage_reservations
    where school_id = p_school_id and usage_year = v_year and exam_id = p_exam_id;

    if not exists (
        select 1 from public.gemini_ai_usage_reservations
        where school_id = p_school_id and usage_year = v_year and exam_id = p_exam_id
    ) and v_uploads >= v_policy.annual_upload_limit then
        return jsonb_build_object(
            'allowed', false,
            'code', 'ANNUAL_UPLOAD_LIMIT_REACHED',
            'message', 'The school has reached its annual AI upload allowance.',
            'usage_year', v_year,
            'uploads_used', v_uploads,
            'upload_limit', v_policy.annual_upload_limit,
            'papers_in_upload', v_papers_in_batch,
            'papers_per_upload_limit', v_policy.exams_per_upload_limit
        );
    end if;

    if v_papers_in_batch >= v_policy.exams_per_upload_limit then
        return jsonb_build_object(
            'allowed', false,
            'code', 'UPLOAD_EXAM_LIMIT_REACHED',
            'message', 'This AI upload batch has reached its examination paper limit.',
            'usage_year', v_year,
            'uploads_used', v_uploads,
            'upload_limit', v_policy.annual_upload_limit,
            'papers_in_upload', v_papers_in_batch,
            'papers_per_upload_limit', v_policy.exams_per_upload_limit
        );
    end if;

    insert into public.gemini_ai_usage_reservations
        (school_id, usage_year, exam_id, exam_paper_id, actor_user_id, status)
    values
        (p_school_id, v_year, p_exam_id, p_exam_paper_id, p_actor_user_id, 'reserved')
    on conflict (school_id, usage_year, exam_paper_id) do nothing;

    select count(distinct exam_id)::integer into v_uploads
    from public.gemini_ai_usage_reservations
    where school_id = p_school_id and usage_year = v_year;

    select count(*)::integer into v_papers_in_batch
    from public.gemini_ai_usage_reservations
    where school_id = p_school_id and usage_year = v_year and exam_id = p_exam_id;

    return jsonb_build_object(
        'allowed', true,
        'already_reserved', false,
        'usage_year', v_year,
        'uploads_used', v_uploads,
        'upload_limit', v_policy.annual_upload_limit,
        'papers_in_upload', v_papers_in_batch,
        'papers_per_upload_limit', v_policy.exams_per_upload_limit
    );
end;
$$;

revoke all on function public.reserve_gemini_ai_analysis_slot(bigint,bigint,bigint,uuid) from public, anon, authenticated;
grant execute on function public.reserve_gemini_ai_analysis_slot(bigint,bigint,bigint,uuid) to service_role;

create or replace function public.get_ai_usage_admin_overview(p_year integer default null)
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
with selected_year as (
    select coalesce(p_year, extract(year from (now() at time zone 'Africa/Dar_es_Salaam'))::integer) as year
),
reservation_totals as (
    select r.school_id,
           count(distinct r.exam_id)::integer as uploads_used,
           count(*)::integer as exams_used,
           max(r.reserved_at) as last_upload_at
    from public.gemini_ai_usage_reservations r, selected_year y
    where r.usage_year = y.year
    group by r.school_id
),
cost_totals as (
    select l.school_id,
           count(*)::integer as analyses_recorded,
           coalesce(sum(l.request_count),0)::bigint as gemini_requests,
           coalesce(sum(l.retry_count),0)::bigint as retries,
           coalesce(sum(l.total_tokens),0)::bigint as total_tokens,
           coalesce(sum(l.prompt_tokens),0)::bigint as input_tokens,
           coalesce(sum(coalesce(l.candidates_tokens,0) + coalesce(l.thoughts_tokens,0)),0)::bigint as output_tokens,
           case when bool_or(l.estimated_cost_usd is null) then null else coalesce(sum(l.estimated_cost_usd),0)::numeric end as estimated_cost_usd,
           case when bool_or(l.estimated_cost_tzs is null) then null else coalesce(sum(l.estimated_cost_tzs),0)::numeric end as estimated_cost_tzs,
           count(*) filter (where l.pricing_status <> 'estimated')::integer as unpriced_analyses,
           max(l.created_at) as last_analysis_at
    from public.gemini_usage_logs l, selected_year y
    where l.created_at >= make_timestamptz(y.year,1,1,0,0,0,'Africa/Dar_es_Salaam')
      and l.created_at < make_timestamptz(y.year + 1,1,1,0,0,0,'Africa/Dar_es_Salaam')
    group by l.school_id
)
select coalesce(jsonb_agg(jsonb_build_object(
    'school_id', s.id,
    'school_name', s.school_name,
    'is_school_active', s.is_active,
    'ai_enabled', coalesce(p.is_enabled,true),
    'annual_upload_limit', coalesce(p.annual_upload_limit,10),
    'exams_per_upload_limit', coalesce(p.exams_per_upload_limit,20),
    'uploads_used', coalesce(r.uploads_used,0),
    'uploads_remaining', greatest(0,coalesce(p.annual_upload_limit,10)-coalesce(r.uploads_used,0)),
    'exams_used', coalesce(r.exams_used,0),
    'analyses_recorded', coalesce(c.analyses_recorded,0),
    'gemini_requests', coalesce(c.gemini_requests,0),
    'retries', coalesce(c.retries,0),
    'input_tokens', coalesce(c.input_tokens,0),
    'output_tokens', coalesce(c.output_tokens,0),
    'total_tokens', coalesce(c.total_tokens,0),
    'estimated_cost_usd', c.estimated_cost_usd,
    'estimated_cost_tzs', c.estimated_cost_tzs,
    'unpriced_analyses', coalesce(c.unpriced_analyses,0),
    'last_upload_at', r.last_upload_at,
    'last_analysis_at', c.last_analysis_at
) order by s.school_name), '[]'::jsonb)
from public.schools s
left join public.gemini_ai_usage_policies p on p.school_id = s.id
left join reservation_totals r on r.school_id = s.id
left join cost_totals c on c.school_id = s.id;
$$;

create or replace function public.get_ai_usage_school_detail(p_school_id bigint, p_year integer default null)
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
with selected_year as (
    select coalesce(p_year, extract(year from (now() at time zone 'Africa/Dar_es_Salaam'))::integer) as year
),
reservation_batches as (
    select r.exam_id,
           count(*)::integer as papers_used,
           min(r.reserved_at) as started_at,
           max(r.reserved_at) as last_upload_at,
           count(*) filter (where r.status = 'completed')::integer as completed,
           count(*) filter (where r.status = 'failed')::integer as failed
    from public.gemini_ai_usage_reservations r, selected_year y
    where r.school_id = p_school_id and r.usage_year = y.year
    group by r.exam_id
),
monthly_costs as (
    select to_char(date_trunc('month', l.created_at at time zone 'Africa/Dar_es_Salaam'), 'YYYY-MM') as month,
           count(*)::integer as analyses,
           coalesce(sum(l.total_tokens),0)::bigint as tokens,
           case when bool_or(l.estimated_cost_usd is null) then null else coalesce(sum(l.estimated_cost_usd),0)::numeric end as cost_usd,
           case when bool_or(l.estimated_cost_tzs is null) then null else coalesce(sum(l.estimated_cost_tzs),0)::numeric end as cost_tzs
    from public.gemini_usage_logs l, selected_year y
    where l.school_id = p_school_id
      and l.created_at >= make_timestamptz(y.year,1,1,0,0,0,'Africa/Dar_es_Salaam')
      and l.created_at < make_timestamptz(y.year + 1,1,1,0,0,0,'Africa/Dar_es_Salaam')
    group by date_trunc('month', l.created_at at time zone 'Africa/Dar_es_Salaam')
),
recent_logs as (
    select jsonb_agg(jsonb_build_object(
        'id', q.id, 'exam_id', q.exam_id, 'exam_subject_id', q.exam_subject_id,
        'exam_paper_id', q.exam_paper_id, 'model', q.model,
        'request_count', q.request_count, 'retry_count', q.retry_count,
        'total_tokens', q.total_tokens, 'estimated_cost_usd', q.estimated_cost_usd,
        'estimated_cost_tzs', q.estimated_cost_tzs, 'pricing_status', q.pricing_status,
        'created_at', q.created_at
    ) order by q.created_at desc) as items
    from (
        select l.* from public.gemini_usage_logs l, selected_year y
        where l.school_id = p_school_id
          and l.created_at >= make_timestamptz(y.year,1,1,0,0,0,'Africa/Dar_es_Salaam')
          and l.created_at < make_timestamptz(y.year + 1,1,1,0,0,0,'Africa/Dar_es_Salaam')
        order by l.created_at desc limit 50
    ) q
)
select jsonb_build_object(
    'school', (select jsonb_build_object('id', s.id, 'name', s.school_name, 'is_active', s.is_active) from public.schools s where s.id = p_school_id),
    'year', (select year from selected_year),
    'policy', (select jsonb_build_object(
        'is_enabled', coalesce(p.is_enabled,true),
        'annual_upload_limit', coalesce(p.annual_upload_limit,10),
        'exams_per_upload_limit', coalesce(p.exams_per_upload_limit,20),
        'admin_note', p.admin_note
    ) from public.gemini_ai_usage_policies p where p.school_id = p_school_id),
    'usage', (select jsonb_build_object(
        'uploads_used', coalesce(count(distinct r.exam_id),0),
        'exams_used', coalesce(count(r.id),0)
    ) from public.gemini_ai_usage_reservations r, selected_year y where r.school_id = p_school_id and r.usage_year = y.year),
    'batches', coalesce((select jsonb_agg(to_jsonb(b) order by b.last_upload_at desc) from reservation_batches b),'[]'::jsonb),
    'monthly', coalesce((select jsonb_agg(to_jsonb(m) order by m.month desc) from monthly_costs m),'[]'::jsonb),
    'recent', coalesce((select items from recent_logs),'[]'::jsonb)
);
$$;

revoke all on function public.get_ai_usage_admin_overview(integer) from public, anon, authenticated;
revoke all on function public.get_ai_usage_school_detail(bigint,integer) from public, anon, authenticated;
