-- AfriCore Transport Management foundation.
-- This migration is intentionally additive: it reuses existing schools, employees,
-- students and Finance ledgers. No existing records are modified or deleted.

create table if not exists public.transport_vehicles (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools(id) on delete cascade,
  registration_number text not null,
  make text,
  model text,
  manufacture_year integer,
  seating_capacity integer not null check (seating_capacity > 0),
  vehicle_type text not null default 'bus',
  status text not null default 'active'
    check (status in ('active','maintenance','inactive','retired')),
  insurance_expiry date,
  inspection_expiry date,
  notes text,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint transport_vehicle_registration_uq unique (school_id, registration_number)
);

create unique index if not exists transport_vehicles_id_school_uq
  on public.transport_vehicles(id, school_id);

create table if not exists public.transport_routes (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools(id) on delete cascade,
  vehicle_id bigint not null,
  route_name text not null,
  start_location text,
  end_location text,
  departure_time time,
  return_time time,
  monthly_fee numeric(14,2) not null default 0 check (monthly_fee >= 0),
  status text not null default 'active' check (status in ('active','inactive')),
  notes text,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint transport_route_vehicle_fk
    foreign key (vehicle_id, school_id)
    references public.transport_vehicles(id, school_id) deferrable initially immediate
);

create unique index if not exists transport_routes_id_school_uq
  on public.transport_routes(id, school_id);

create table if not exists public.transport_route_stops (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools(id) on delete cascade,
  route_id bigint not null,
  stop_name text not null,
  stop_order integer not null check (stop_order > 0),
  pickup_time time,
  dropoff_time time,
  created_at timestamptz not null default now(),
  constraint transport_stop_route_fk
    foreign key (route_id, school_id)
    references public.transport_routes(id, school_id) on delete cascade,
  constraint transport_stop_order_uq unique (route_id, stop_order)
);

create unique index if not exists transport_route_stops_id_route_school_uq
  on public.transport_route_stops(id, route_id, school_id);

create unique index if not exists transport_student_id_school_uq
  on public.students(id, school_id);
create unique index if not exists transport_employee_id_school_uq
  on public.employees(id, school_id);

create table if not exists public.transport_vehicle_crew (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools(id) on delete cascade,
  vehicle_id bigint not null,
  employee_id bigint not null references public.employees(id) on delete restrict,
  crew_role text not null check (crew_role in ('driver','conductor')),
  start_date date not null default current_date,
  end_date date,
  is_active boolean not null default true,
  assigned_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  constraint transport_crew_vehicle_fk
    foreign key (vehicle_id, school_id)
    references public.transport_vehicles(id, school_id) on delete cascade,
  constraint transport_crew_employee_school_fk
    foreign key (employee_id, school_id)
    references public.employees(id, school_id) on delete restrict,
  constraint transport_crew_dates_check check (end_date is null or end_date >= start_date)
);

create unique index if not exists transport_vehicle_active_crew_role_uq
  on public.transport_vehicle_crew(vehicle_id, crew_role)
  where is_active = true;

create table if not exists public.transport_student_assignments (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools(id) on delete cascade,
  student_id bigint not null,
  route_id bigint not null,
  pickup_stop_id bigint,
  dropoff_stop_id bigint,
  start_date date not null default current_date,
  end_date date,
  monthly_fee numeric(14,2) not null default 0 check (monthly_fee >= 0),
  is_active boolean not null default true,
  assigned_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  constraint transport_student_school_fk
    foreign key (student_id, school_id)
    references public.students(id, school_id) on delete restrict,
  constraint transport_assignment_route_fk
    foreign key (route_id, school_id)
    references public.transport_routes(id, school_id) on delete restrict,
  constraint transport_assignment_pickup_fk
    foreign key (pickup_stop_id, route_id, school_id)
    references public.transport_route_stops(id, route_id, school_id) on delete restrict,
  constraint transport_assignment_dropoff_fk
    foreign key (dropoff_stop_id, route_id, school_id)
    references public.transport_route_stops(id, route_id, school_id) on delete restrict,
  constraint transport_student_assignment_dates_check check (end_date is null or end_date >= start_date)
);

create unique index if not exists transport_student_one_active_route_uq
  on public.transport_student_assignments(school_id, student_id)
  where is_active = true;

create table if not exists public.transport_finance_transactions (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools(id) on delete cascade,
  transaction_number text not null,
  transaction_type text not null check (transaction_type in ('income','expense')),
  category text not null,
  description text not null,
  amount numeric(14,2) not null check (amount > 0),
  transaction_date date not null default current_date,
  student_id bigint,
  payer_name text,
  employee_id bigint,
  revenue_account_id uuid references finance.chart_of_accounts(id),
  expense_account_id uuid references finance.chart_of_accounts(id),
  cash_account_id bigint references finance.cash_accounts(id),
  payment_method text check (payment_method is null or payment_method in ('cash','bank','mobile_money','cheque','other')),
  reference_number text,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  receipt_id uuid references finance.receipts(id) on delete set null,
  expense_id bigint references public.expenses(id) on delete set null,
  journal_entry_id uuid references finance.journal_entries(id) on delete set null,
  submitted_by uuid not null references auth.users(id),
  submitted_at timestamptz not null default now(),
  reviewed_by uuid references auth.users(id),
  reviewed_at timestamptz,
  rejection_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint transport_finance_number_uq unique (school_id, transaction_number),
  constraint transport_finance_student_school_fk
    foreign key (student_id, school_id)
    references public.students(id, school_id) on delete restrict,
  constraint transport_finance_employee_school_fk
    foreign key (employee_id, school_id)
    references public.employees(id, school_id) on delete restrict,
  constraint transport_finance_account_shape_check check (
    (transaction_type = 'income' and revenue_account_id is not null and expense_account_id is null)
    or
    (transaction_type = 'expense' and expense_account_id is not null and revenue_account_id is null)
  )
);

create index if not exists transport_finance_status_idx
  on public.transport_finance_transactions(school_id, status, transaction_date desc);
create index if not exists transport_assignments_route_idx
  on public.transport_student_assignments(school_id, route_id, is_active);
create index if not exists transport_crew_vehicle_idx
  on public.transport_vehicle_crew(school_id, vehicle_id, is_active);

-- Tenant-scoped read access. Writes are reserved for authenticated RPCs added
-- with the application workflow; direct client writes are deliberately denied.
do $$
declare
  t text;
begin
  foreach t in array array[
    'transport_vehicles',
    'transport_routes',
    'transport_route_stops',
    'transport_vehicle_crew',
    'transport_student_assignments',
    'transport_finance_transactions'
  ] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists %I on public.%I', t || '_tenant_read', t);
    execute format(
      'create policy %I on public.%I for select to authenticated using (public.is_current_user_super_admin() or school_id = public.get_current_user_school_id())',
      t || '_tenant_read', t
    );
    execute format('revoke insert, update, delete on public.%I from anon, authenticated', t);
    execute format('grant select on public.%I to authenticated', t);
  end loop;
end $$;

-- Transport-specific permissions are additive and preserve existing role grants.
insert into public.permissions (module, permission_name, description, is_active, module_name, action_name)
select 'transport', v.permission_name, v.description, true, 'Transport Management', v.action_name
from (values
  ('view_transport', 'View transport vehicles, routes, crew and student allocations.', 'view'),
  ('manage_transport', 'Manage transport vehicles, routes, crew and student allocations.', 'manage'),
  ('manage_transport_finance', 'Submit transport income and expense transactions.', 'manage'),
  ('approve_transport_finance', 'Approve or reject transport finance transactions.', 'approve')
) as v(permission_name, description, action_name)
where not exists (
  select 1 from public.permissions p where p.permission_name = v.permission_name
);

insert into public.role_permissions (role_id, permission_id)
select r.id, p.id
from public.roles r
join public.permissions p on p.permission_name = case
  when lower(trim(r.role_name)) = 'secretary' then 'manage_transport'
  when lower(trim(r.role_name)) = 'accountant' then 'manage_transport_finance'
  when lower(trim(r.role_name)) = 'hr manager' then 'approve_transport_finance'
  when lower(trim(r.role_name)) in ('headmaster','super admin') then 'view_transport'
end
where lower(trim(r.role_name)) in ('secretary','accountant','hr manager','headmaster','super admin')
and not exists (
  select 1 from public.role_permissions rp
  where rp.role_id = r.id and rp.permission_id = p.id
);

-- Accountants, HR Managers and school leadership can inspect transport finance;
-- the approval permission itself remains restricted to HR Manager by the RPC layer.
insert into public.role_permissions (role_id, permission_id)
select r.id, p.id
from public.roles r
join public.permissions p on p.permission_name = 'view_transport'
where lower(trim(r.role_name)) in ('accountant','hr manager','headmaster','super admin')
and not exists (
  select 1 from public.role_permissions rp
  where rp.role_id = r.id and rp.permission_id = p.id
);
