begin;

-- Optional assessment components. An empty array preserves the existing
-- question-by-question marks workflow without changing historical records.
alter table public.exam_subjects
    add column if not exists assessment_components jsonb not null default '[]'::jsonb;

alter table public.exam_subjects
    drop constraint if exists exam_subjects_assessment_components_array_check;

alter table public.exam_subjects
    add constraint exam_subjects_assessment_components_array_check
    check (jsonb_typeof(assessment_components) = 'array');

-- Store the raw mark entered for each optional Test/Practical component.
create table if not exists public.exam_assessment_marks (
    id bigint generated by default as identity primary key,
    exam_id bigint not null references public.exams(id) on delete cascade,
    exam_subject_id bigint not null references public.exam_subjects(id) on delete cascade,
    student_id bigint not null references public.students(id) on delete cascade,
    component_key text not null,
    marks_obtained numeric(10,2) not null default 0,
    created_at timestamp without time zone not null default now(),
    created_by uuid,
    constraint exam_assessment_marks_component_key_check
        check (length(trim(component_key)) > 0),
    constraint exam_assessment_marks_nonnegative_check
        check (marks_obtained >= 0),
    constraint exam_assessment_marks_unique
        unique (exam_subject_id, student_id, component_key)
);

create index if not exists idx_exam_assessment_marks_exam_id
    on public.exam_assessment_marks(exam_id);
create index if not exists idx_exam_assessment_marks_exam_subject_id
    on public.exam_assessment_marks(exam_subject_id);
create index if not exists idx_exam_assessment_marks_student_id
    on public.exam_assessment_marks(student_id);

-- Speed up the final-mark upsert lookup used by Enter Marks.
create index if not exists idx_exam_marks_exam_subject_student_created_at
    on public.exam_marks(exam_id, exam_subject_id, student_id, created_at desc);

alter table public.exam_assessment_marks enable row level security;

drop policy if exists af_score_exam_assessment_marks_authenticated_base
    on public.exam_assessment_marks;
create policy af_score_exam_assessment_marks_authenticated_base
    on public.exam_assessment_marks
    for all
    to authenticated
    using (true)
    with check (true);

drop policy if exists af_score_exam_assessment_marks_tenant_guard
    on public.exam_assessment_marks;
create policy af_score_exam_assessment_marks_tenant_guard
    on public.exam_assessment_marks
    as restrictive
    for all
    to authenticated
    using (
        public.is_current_user_super_admin()
        or (
            exists (
                select 1
                from public.exams e
                where e.id = exam_assessment_marks.exam_id
                  and e.school_id = public.get_current_user_school_id()
            )
            and exists (
                select 1
                from public.students st
                where st.id = exam_assessment_marks.student_id
                  and st.school_id = public.get_current_user_school_id()
            )
            and exists (
                select 1
                from public.exam_subjects es
                where es.id = exam_assessment_marks.exam_subject_id
                  and es.exam_id = exam_assessment_marks.exam_id
            )
        )
    )
    with check (
        public.is_current_user_super_admin()
        or (
            exists (
                select 1
                from public.exams e
                where e.id = exam_assessment_marks.exam_id
                  and e.school_id = public.get_current_user_school_id()
            )
            and exists (
                select 1
                from public.students st
                where st.id = exam_assessment_marks.student_id
                  and st.school_id = public.get_current_user_school_id()
            )
            and exists (
                select 1
                from public.exam_subjects es
                where es.id = exam_assessment_marks.exam_subject_id
                  and es.exam_id = exam_assessment_marks.exam_id
            )
        )
    );

grant select, insert, update, delete on public.exam_assessment_marks to authenticated;
grant usage, select on sequence public.exam_assessment_marks_id_seq to authenticated;

commit;
