begin;

create table if not exists public.exam_student_assessment_setups (
    id bigint generated by default as identity primary key,
    exam_id bigint not null references public.exams(id) on delete cascade,
    exam_subject_id bigint not null references public.exam_subjects(id) on delete cascade,
    student_id bigint not null references public.students(id) on delete cascade,
    assessment_components jsonb not null default '[]'::jsonb,
    created_at timestamp without time zone not null default now(),
    updated_at timestamp without time zone not null default now(),
    created_by uuid,
    constraint exam_student_assessment_setups_components_array_check
        check (jsonb_typeof(assessment_components) = 'array'),
    constraint exam_student_assessment_setups_unique
        unique (exam_subject_id, student_id)
);

create index if not exists idx_exam_student_assessment_setups_exam_id
    on public.exam_student_assessment_setups(exam_id);
create index if not exists idx_exam_student_assessment_setups_student_id
    on public.exam_student_assessment_setups(student_id);

alter table public.exam_student_assessment_setups enable row level security;

drop policy if exists exam_student_assessment_setups_tenant_access
    on public.exam_student_assessment_setups;

create policy exam_student_assessment_setups_tenant_access
    on public.exam_student_assessment_setups
    for all
    to authenticated
    using (
        public.is_current_user_super_admin()
        or (
            exists (
                select 1
                from public.exams e
                where e.id = exam_student_assessment_setups.exam_id
                  and e.school_id = public.get_current_user_school_id()
            )
            and exists (
                select 1
                from public.students st
                where st.id = exam_student_assessment_setups.student_id
                  and st.school_id = public.get_current_user_school_id()
            )
            and exists (
                select 1
                from public.exam_subjects es
                where es.id = exam_student_assessment_setups.exam_subject_id
                  and es.exam_id = exam_student_assessment_setups.exam_id
            )
        )
    )
    with check (
        public.is_current_user_super_admin()
        or (
            exists (
                select 1
                from public.exams e
                where e.id = exam_student_assessment_setups.exam_id
                  and e.school_id = public.get_current_user_school_id()
            )
            and exists (
                select 1
                from public.students st
                where st.id = exam_student_assessment_setups.student_id
                  and st.school_id = public.get_current_user_school_id()
            )
            and exists (
                select 1
                from public.exam_subjects es
                where es.id = exam_student_assessment_setups.exam_subject_id
                  and es.exam_id = exam_student_assessment_setups.exam_id
            )
        )
    );

grant select, insert, update, delete
    on public.exam_student_assessment_setups to authenticated;
grant usage, select
    on sequence public.exam_student_assessment_setups_id_seq to authenticated;

commit;

-- Preserve the previous setup only for students who already had assessment marks.
-- Students without saved assessment marks start with no optional components.
insert into public.exam_student_assessment_setups
    (exam_id, exam_subject_id, student_id, assessment_components, created_at, updated_at)
select distinct
    es.exam_id, es.id, eam.student_id, es.assessment_components, now(), now()
from public.exam_assessment_marks eam
join public.exam_subjects es on es.id = eam.exam_subject_id
where jsonb_typeof(es.assessment_components) = 'array'
  and jsonb_array_length(es.assessment_components) > 0
on conflict (exam_subject_id, student_id) do nothing;
