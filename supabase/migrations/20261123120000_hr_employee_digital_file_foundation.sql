-- Employee Digital File foundation.
-- Canonical employee identity remains public.employees.id. This migration adds
-- only extension records and does not create or rewrite employee rows.

begin;

-- Composite parent key prevents an HR row from pairing an employee ID with a forged school ID.
create unique index if not exists employees_id_school_id_uidx
  on public.employees(id, school_id);

-- Existing tenant_guard policies on these legacy tables are RESTRICTIVE.
-- PostgreSQL combines permissive policies with OR, then restrictive policies
-- with AND. The existing authenticated_base policies provide the permissive
-- grant while the restrictive tenant guards enforce school isolation.
-- Preserve both: dropping the permissive policy would deny legitimate access.

create table if not exists public.hr_employee_profiles (
  employee_id bigint primary key,
  school_id bigint not null references public.schools(id) on delete restrict,
  date_of_birth date,
  nationality text,
  national_id text,
  marital_status text,
  residential_address text,
  postal_address text,
  personal_email text,
  alternative_phone text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  constraint hr_employee_profiles_employee_school_fkey
    foreign key (employee_id, school_id) references public.employees(id, school_id) on delete cascade,
  constraint hr_employee_profiles_marital_status_check
    check (marital_status is null or marital_status in ('single','married','divorced','widowed','other'))
);

create table if not exists public.hr_employee_contacts (
  id bigint generated by default as identity primary key,
  employee_id bigint not null,
  school_id bigint not null references public.schools(id) on delete restrict,
  constraint hr_employee_contacts_employee_school_fkey
    foreign key (employee_id, school_id) references public.employees(id, school_id) on delete cascade,
  contact_name text not null,
  relationship text,
  phone text not null,
  email text,
  address text,
  is_primary boolean not null default false,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid references auth.users(id) on delete set null
);

create unique index if not exists hr_employee_contacts_one_primary_uidx
  on public.hr_employee_contacts(employee_id)
  where is_primary is true;

create index if not exists hr_employee_contacts_school_employee_idx
  on public.hr_employee_contacts(school_id, employee_id);

create table if not exists public.hr_employment_history (
  id bigint generated by default as identity primary key,
  employee_id bigint not null,
  school_id bigint not null references public.schools(id) on delete restrict,
  constraint hr_employment_history_employee_school_fkey
    foreign key (employee_id, school_id) references public.employees(id, school_id) on delete restrict,
  event_type text not null,
  event_date date not null,
  previous_department text,
  new_department text,
  previous_position text,
  new_position text,
  description text not null,
  reference_number text,
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id) on delete set null,
  constraint hr_employment_history_event_type_check
    check (event_type in ('appointment','confirmation','promotion','transfer','salary_review','disciplinary','termination','rehire','other'))
);

create index if not exists hr_employment_history_school_employee_date_idx
  on public.hr_employment_history(school_id, employee_id, event_date desc);

alter table public.hr_employee_profiles enable row level security;
alter table public.hr_employee_contacts enable row level security;
alter table public.hr_employment_history enable row level security;

drop policy if exists hr_employee_profiles_select_scope on public.hr_employee_profiles;
create policy hr_employee_profiles_select_scope
on public.hr_employee_profiles for select to authenticated
using (
  public.is_current_user_super_admin()
  or exists (
    select 1 from public.profile_roles pr
    join public.roles r on r.id = pr.role_id
    where pr.profile_id = (select auth.uid())
      and pr.is_active is true
      and pr.school_id = hr_employee_profiles.school_id
      and lower(trim(r.role_name)) in ('hr manager','headmaster')
  )
  or exists (
    select 1 from public.employees e
    left join public.profiles p on p.id = (select auth.uid())
    where e.id = hr_employee_profiles.employee_id
      and e.school_id = hr_employee_profiles.school_id
      and (e.user_id = (select auth.uid()) or p.employee_id = e.id or (p.teacher_id is not null and p.teacher_id = e.source_teacher_id))
  )
);

drop policy if exists hr_employee_profiles_manage_hr on public.hr_employee_profiles;
create policy hr_employee_profiles_manage_hr
on public.hr_employee_profiles for all to authenticated
using (
