-- ZK9500 Windows Agent pairing and local-only fingerprint enrollment metadata.
-- No fingerprint image or biometric template is stored in Supabase.

alter table public.hr_biometric_devices
  add column if not exists agent_token_hash text,
  add column if not exists paired_at timestamptz,
  add column if not exists agent_version text,
  add column if not exists last_error text;

create table if not exists public.hr_biometric_enrollments (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools(id) on delete cascade,
  device_id bigint not null,
  employee_id bigint not null,
  finger_slot smallint not null default 1 check (finger_slot between 1 and 10),
  status text not null default 'active' check (status in ('active','revoked')),
  enrolled_at timestamptz not null default now(),
  revoked_at timestamptz,
  created_by uuid references auth.users(id) on delete set null,
  unique (school_id, device_id, employee_id, finger_slot),
  foreign key (school_id, device_id)
    references public.hr_biometric_devices(school_id, id) on delete cascade,
  foreign key (school_id, employee_id)
    references public.employees(school_id, id) on delete cascade
);

alter table public.hr_biometric_enrollments enable row level security;
drop policy if exists hr_biometric_enrollments_school_scope on public.hr_biometric_enrollments;
create policy hr_biometric_enrollments_school_scope
on public.hr_biometric_enrollments for all to authenticated
using (
  public.is_current_user_super_admin()
  or school_id in (
    select pr.school_id from public.profile_roles pr
    join public.roles r on r.id = pr.role_id
    where pr.profile_id = auth.uid() and pr.is_active is true
      and lower(trim(r.role_name)) in ('hr manager','headmaster')
  )
)
with check (
  public.is_current_user_super_admin()
  or school_id in (
    select pr.school_id from public.profile_roles pr
    join public.roles r on r.id = pr.role_id
    where pr.profile_id = auth.uid() and pr.is_active is true
      and lower(trim(r.role_name)) in ('hr manager','headmaster')
  )
);

create index if not exists hr_biometric_enrollments_employee_idx
  on public.hr_biometric_enrollments(school_id, employee_id, status);
create index if not exists hr_biometric_devices_agent_hash_idx
  on public.hr_biometric_devices(agent_token_hash)
  where agent_token_hash is not null;
