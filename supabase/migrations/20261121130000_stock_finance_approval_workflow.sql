-- Controlled accounting hand-off for stock purchases and parent/student stock payments.
-- Requests remain outside official Finance ledgers until the Headmaster approves them.

create table if not exists public.stock_finance_approval_requests (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools(id) on delete cascade,
  request_type text not null check (request_type in ('purchase_receipt','student_order_payment')),
  source_movement_id bigint references public.stock_movements(id) on delete restrict,
  source_payment_id bigint references public.stock_student_order_payments(id) on delete restrict,
  amount numeric(14,2) not null check (amount > 0),
  transaction_date date not null,
  description text not null,
  reference_number text,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  expense_id bigint references public.expenses(id) on delete set null,
  receipt_id uuid references finance.receipts(id) on delete set null,
  journal_entry_id uuid references finance.journal_entries(id) on delete set null,
  submitted_by uuid references auth.users(id),
  submitted_at timestamptz not null default now(),
  approved_by uuid references auth.users(id),
  approved_at timestamptz,
  rejected_by uuid references auth.users(id),
  rejected_at timestamptz,
  rejection_reason text,
  created_at timestamptz not null default now(),
  constraint stock_finance_request_source_check check (
    (request_type = 'purchase_receipt' and source_movement_id is not null and source_payment_id is null)
    or
    (request_type = 'student_order_payment' and source_payment_id is not null and source_movement_id is null)
  )
);

create unique index if not exists stock_finance_request_movement_uq
  on public.stock_finance_approval_requests(school_id, source_movement_id)
  where source_movement_id is not null;
create unique index if not exists stock_finance_request_payment_uq
  on public.stock_finance_approval_requests(school_id, source_payment_id)
  where source_payment_id is not null;
create index if not exists stock_finance_request_status_idx
  on public.stock_finance_approval_requests(school_id, status, created_at desc);

alter table public.stock_finance_approval_requests enable row level security;
drop policy if exists stock_finance_approval_requests_select on public.stock_finance_approval_requests;
create policy stock_finance_approval_requests_select
on public.stock_finance_approval_requests for select to authenticated
using (
  public.is_current_user_super_admin()
  or (
    school_id = public.get_current_user_school_id()
    and exists (
      select 1
      from public.profile_roles pr
      join public.roles r on r.id = pr.role_id
      where pr.profile_id = auth.uid()
        and pr.school_id = stock_finance_approval_requests.school_id
        and pr.is_active is true
        and lower(trim(r.role_name)) in ('accountant','headmaster')
    )
  )
);

grant select on public.stock_finance_approval_requests to authenticated;
grant usage, select on sequence public.stock_finance_approval_requests_id_seq to authenticated;
revoke insert, update, delete on public.stock_finance_approval_requests from anon, authenticated;

create or replace function public.submit_stock_finance_approval_request(
  p_request_type text,
  p_source_id bigint
)
returns jsonb
language plpgsql
security definer
set search_path = public, finance, pg_temp
as $$
declare
  v_school_id bigint;
  v_user uuid := auth.uid();
  v_movement public.stock_movements%rowtype;
  v_payment public.stock_student_order_payments%rowtype;
  v_order public.stock_purchase_orders%rowtype;
  v_student_order public.stock_student_orders%rowtype;
  v_student public.students%rowtype;
  v_amount numeric(14,2);
  v_description text;
  v_request_id bigint;
begin
  if v_user is null then raise exception 'Authentication is required.'; end if;
  v_school_id := public.get_current_user_school_id();
  if v_school_id is null then raise exception 'Active school is not configured.'; end if;

  if not public.is_current_user_super_admin() and not exists (
    select 1 from public.profile_roles pr
    join public.roles r on r.id = pr.role_id
    where pr.profile_id = v_user and pr.school_id = v_school_id
      and pr.is_active is true
      and lower(trim(r.role_name)) in ('accountant','headmaster')
  ) then
    raise exception 'Only the school Accountant or Headmaster may submit stock records to Finance.';
  end if;

  if p_request_type = 'purchase_receipt' then
    select * into v_movement
    from public.stock_movements
    where id = p_source_id and school_id = v_school_id and movement_type = 'receive'
    for update;
    if not found then raise exception 'Received stock movement was not found.'; end if;

    select * into v_order
    from public.stock_purchase_orders
    where school_id = v_school_id and order_number = v_movement.reference_number
    limit 1;
    if not found then raise exception 'Related purchase order was not found.'; end if;
    if v_order.status not in ('partially_received','received') then
      raise exception 'Only goods received against an approved purchase order can be sent to Finance.';
    end if;
    v_amount := round(v_movement.quantity * v_movement.unit_cost, 2);
    if v_amount <= 0 then raise exception 'This received movement has no recorded purchase cost.'; end if;
    select item_name into v_description from public.stock_items
    where id = v_movement.item_id and school_id = v_school_id;
    v_description := 'Stock purchase ' || v_order.order_number || ' - ' || coalesce(v_description,'item');
    insert into public.stock_finance_approval_requests (
      school_id, request_type, source_movement_id, amount, transaction_date,
      description, reference_number, submitted_by
    ) values (
      v_school_id, 'purchase_receipt', v_movement.id, v_amount, v_movement.movement_date,
      v_description, v_order.order_number, v_user
    )
    on conflict (school_id, source_movement_id) where source_movement_id is not null
    do update set id = public.stock_finance_approval_requests.id
    returning id into v_request_id;

  elsif p_request_type = 'student_order_payment' then
    select * into v_payment
    from public.stock_student_order_payments
    where id = p_source_id and school_id = v_school_id
    for update;
    if not found then raise exception 'Student order payment was not found.'; end if;

    select * into v_student_order
    from public.stock_student_orders
    where id = v_payment.student_order_id and school_id = v_school_id;
    if not found or v_student_order.status = 'cancelled' then
      raise exception 'The related student order is unavailable or cancelled.';
    end if;
    select * into v_student from public.students
    where id = v_student_order.student_id and school_id = v_school_id;

    v_amount := v_payment.amount;
    v_description := 'Parent/student stock order payment ' || v_student_order.order_number;
    insert into public.stock_finance_approval_requests (
      school_id, request_type, source_payment_id, amount, transaction_date,
      description, reference_number, submitted_by
    ) values (
      v_school_id, 'student_order_payment', v_payment.id, v_amount, v_payment.payment_date,
      v_description, coalesce(v_payment.payment_reference, v_student_order.order_number), v_user
    )
    on conflict (school_id, source_payment_id) where source_payment_id is not null
    do update set id = public.stock_finance_approval_requests.id
    returning id into v_request_id;
  else
    raise exception 'Invalid stock Finance request type.';
  end if;

  return jsonb_build_object('success',true,'request_id',v_request_id,'status','pending');
end;
$$;

create or replace function public.approve_stock_finance_request(
  p_request_id bigint,
  p_finance_account_id uuid,
  p_cash_account_id bigint default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, finance, pg_temp
as $$
declare
  v_user uuid := auth.uid();
  v_school_id bigint;
  v_request public.stock_finance_approval_requests%rowtype;
  v_movement public.stock_movements%rowtype;
  v_payment public.stock_student_order_payments%rowtype;
  v_student_order public.stock_student_orders%rowtype;
  v_student public.students%rowtype;
  v_purchase_order public.stock_purchase_orders%rowtype;
  v_expense public.expenses%rowtype;
  v_receipt_id uuid;
  v_journal_id uuid;
  v_receipt_number text;
  v_payment_method text;
begin
  if v_user is null then raise exception 'Authentication is required.'; end if;
  v_school_id := public.get_current_user_school_id();
  if not public.is_current_user_super_admin() and not exists (
    select 1 from public.profile_roles pr
    join public.roles r on r.id = pr.role_id
    where pr.profile_id = v_user and pr.school_id = v_school_id
      and pr.is_active is true and lower(trim(r.role_name)) = 'headmaster'
  ) then
    raise exception 'Only the school Headmaster or Super Admin may approve stock Finance requests.';
  end if;

  select * into v_request
  from public.stock_finance_approval_requests
  where id = p_request_id and school_id = v_school_id
  for update;
  if not found then raise exception 'Finance approval request was not found.'; end if;
  if v_request.status = 'approved' then
    return jsonb_build_object('success',true,'status','approved','expense_id',v_request.expense_id,'receipt_id',v_request.receipt_id,'journal_entry_id',v_request.journal_entry_id);
  end if;
  if v_request.status <> 'pending' then raise exception 'Only pending Finance requests can be approved.'; end if;

  if v_request.request_type = 'purchase_receipt' then
    if p_finance_account_id is null or not exists (
      select 1 from finance.chart_of_accounts
      where id = p_finance_account_id and school_id = v_school_id
        and account_type = 'expense' and is_active = true and allow_manual_posting = true
    ) then raise exception 'Select an active school expense account.'; end if;

    select * into v_movement from public.stock_movements
    where id = v_request.source_movement_id and school_id = v_school_id;
    select * into v_purchase_order from public.stock_purchase_orders
    where school_id = v_school_id and order_number = v_movement.reference_number;
    if v_purchase_order.supplier_id is null then
      raise exception 'This purchase order has no supplier. Add a supplier before approving its expense.';
    end if;

    v_expense := public.create_expense_with_payable(
      v_request.transaction_date,
      'Stock Purchases',
      v_request.description,
      v_request.amount,
      'unpaid',
      null,
      null,
      p_finance_account_id,
      'STOCK-' || v_movement.id::text,
      v_purchase_order.supplier_id,
      'STOCK-' || v_movement.id::text,
      null
    );
    update public.expenses set approved_by = v_user where id = v_expense.id and school_id = v_school_id;
    update public.stock_finance_approval_requests
    set status = 'approved', approved_by = v_user, approved_at = now(),
        expense_id = v_expense.id, journal_entry_id = v_expense.journal_entry_id
    where id = v_request.id;
  else
    if p_finance_account_id is null or not exists (
      select 1 from finance.chart_of_accounts
      where id = p_finance_account_id and school_id = v_school_id
        and account_type = 'revenue' and is_active = true
    ) then raise exception 'Select an active school income account.'; end if;
    if p_cash_account_id is null or not exists (
      select 1 from finance.cash_accounts
      where id = p_cash_account_id and school_id = v_school_id and is_active = true
    ) then raise exception 'Select an active school cash/bank account.'; end if;

    select * into v_payment from public.stock_student_order_payments
    where id = v_request.source_payment_id and school_id = v_school_id;
    select * into v_student_order from public.stock_student_orders
    where id = v_payment.student_order_id and school_id = v_school_id;
    select * into v_student from public.students
    where id = v_student_order.student_id and school_id = v_school_id;

    v_payment_method := case v_payment.payment_method
      when 'bank_transfer' then 'bank'
      when 'mobile_money' then 'mobile_money'
      when 'cash' then 'cash'
      when 'cheque' then 'cheque'
      else 'other'
    end;
    v_receipt_number := 'STOCK-' || v_payment.id::text;
    select receipt_id, journal_entry_id into v_receipt_id, v_journal_id
    from finance.record_receipt(
      v_school_id,
      v_receipt_number,
      v_payment.payment_date,
      v_student_order.student_id,
      coalesce(v_student.parent_name, v_student.guardian_name, 'Parent/Guardian'),
      p_finance_account_id,
      p_cash_account_id,
      v_payment_method,
      v_request.amount,
      coalesce(v_payment.payment_reference, v_student_order.order_number),
      v_request.description,
      v_user,
      v_user
    );
    update public.stock_finance_approval_requests
    set status = 'approved', approved_by = v_user, approved_at = now(),
        receipt_id = v_receipt_id, journal_entry_id = v_journal_id
    where id = v_request.id;
  end if;

  return jsonb_build_object('success',true,'status','approved','expense_id',v_expense.id,'receipt_id',v_receipt_id,'journal_entry_id',coalesce(v_journal_id,v_expense.journal_entry_id));
end;
$$;

create or replace function public.reject_stock_finance_request(
  p_request_id bigint,
  p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path = public, finance, pg_temp
as $$
declare
  v_user uuid := auth.uid();
  v_school_id bigint;
begin
  if v_user is null then raise exception 'Authentication is required.'; end if;
  v_school_id := public.get_current_user_school_id();
  if not public.is_current_user_super_admin() and not exists (
    select 1 from public.profile_roles pr
    join public.roles r on r.id = pr.role_id
    where pr.profile_id = v_user and pr.school_id = v_school_id
      and pr.is_active is true and lower(trim(r.role_name)) = 'headmaster'
  ) then raise exception 'Only the school Headmaster or Super Admin may reject stock Finance requests.'; end if;

  update public.stock_finance_approval_requests
  set status = 'rejected', rejected_by = v_user, rejected_at = now(),
      rejection_reason = nullif(left(trim(coalesce(p_reason,'')),1000),'')
  where id = p_request_id and school_id = v_school_id and status = 'pending';
  if not found then raise exception 'Pending Finance approval request was not found.'; end if;
  return jsonb_build_object('success',true,'status','rejected');
end;
$$;

revoke all on function public.submit_stock_finance_approval_request(text,bigint) from public, anon;
revoke all on function public.approve_stock_finance_request(bigint,uuid,bigint) from public, anon;
revoke all on function public.reject_stock_finance_request(bigint,text) from public, anon;
grant execute on function public.submit_stock_finance_approval_request(text,bigint) to authenticated;
grant execute on function public.approve_stock_finance_request(bigint,uuid,bigint) to authenticated;
grant execute on function public.reject_stock_finance_request(bigint,text) to authenticated;
