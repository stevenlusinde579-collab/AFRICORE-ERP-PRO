-- Annual fee guidance letters are informational only.
-- This table is intentionally isolated from finance.student_charges,
-- student_payment_setups, student_fee_setups, journals and payment RPCs.
create table if not exists public.annual_fee_guidance_setups (
    id bigint generated by default as identity primary key,
    school_id bigint not null references public.schools(id) on delete cascade,
    academic_year_id bigint not null references public.academic_years(id) on delete cascade,
    items jsonb not null default '[]'::jsonb check (jsonb_typeof(items) = 'array'),
    closing_date date,
    reopening_date date,
    intro_message text,
    extra_message text,
    accountant_name text,
    accountant_phone text,
    created_by uuid references auth.users(id) on delete set null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint annual_fee_guidance_setups_school_year_unique unique (school_id, academic_year_id)
);

create index if not exists annual_fee_guidance_setups_school_year_idx
    on public.annual_fee_guidance_setups (school_id, academic_year_id);

alter table public.annual_fee_guidance_setups enable row level security;

drop policy if exists "annual fee guidance school read" on public.annual_fee_guidance_setups;
create policy "annual fee guidance school read"
on public.annual_fee_guidance_setups
for select
to authenticated
using (
    exists (
        select 1
        from public.profiles p
        where p.id = (select auth.uid())
          and p.school_id = annual_fee_guidance_setups.school_id
    )
);

drop policy if exists "annual fee guidance school insert" on public.annual_fee_guidance_setups;
create policy "annual fee guidance school insert"
on public.annual_fee_guidance_setups
for insert
to authenticated
with check (
    exists (
        select 1
        from public.profiles p
        where p.id = (select auth.uid())
          and p.school_id = annual_fee_guidance_setups.school_id
    )
);

drop policy if exists "annual fee guidance school update" on public.annual_fee_guidance_setups;
create policy "annual fee guidance school update"
on public.annual_fee_guidance_setups
for update
to authenticated
using (
    exists (
        select 1
        from public.profiles p
        where p.id = (select auth.uid())
          and p.school_id = annual_fee_guidance_setups.school_id
    )
)
with check (
    exists (
        select 1
        from public.profiles p
        where p.id = (select auth.uid())
          and p.school_id = annual_fee_guidance_setups.school_id
    )
);

grant select, insert, update on public.annual_fee_guidance_setups to authenticated;
grant usage, select on sequence public.annual_fee_guidance_setups_id_seq to authenticated;

create or replace function public.set_annual_fee_guidance_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

drop trigger if exists set_annual_fee_guidance_updated_at on public.annual_fee_guidance_setups;
create trigger set_annual_fee_guidance_updated_at
before update on public.annual_fee_guidance_setups
for each row execute function public.set_annual_fee_guidance_updated_at();

comment on table public.annual_fee_guidance_setups is
'Informational annual school fee and contribution guidance letters only; never used as a receivable, student charge, payment setup, journal or accounting balance.';
