-- Track Gemini API usage and estimated cost per examination analysis.
-- Rows are written only by the trusted backend; browser users cannot read or write this table.
create table if not exists public.gemini_usage_logs (
    id bigint generated by default as identity primary key,
    school_id bigint not null references public.schools(id) on delete restrict,
    exam_id bigint,
    exam_subject_id bigint,
    exam_paper_id bigint,
    analysis_id bigint,
    provider text not null default 'google_gemini',
    model text not null,
    request_count integer not null default 1 check (request_count >= 1),
    retry_count integer not null default 0 check (retry_count >= 0),
    fallback_count integer not null default 0 check (fallback_count >= 0),
    prompt_tokens bigint,
    candidates_tokens bigint,
    thoughts_tokens bigint,
    cached_content_tokens bigint,
    total_tokens bigint,
    input_price_per_million_usd numeric(18,8),
    output_price_per_million_usd numeric(18,8),
    estimated_cost_usd numeric(18,10),
    usd_to_tzs numeric(18,6),
    estimated_cost_tzs numeric(18,4),
    pricing_status text not null default 'estimated'
        check (pricing_status in ('estimated','missing_model_rate','missing_usage_metadata')),
    pricing_source text,
    duration_ms integer,
    created_at timestamptz not null default now()
);

create index if not exists gemini_usage_logs_school_created_idx
    on public.gemini_usage_logs (school_id, created_at desc);
create index if not exists gemini_usage_logs_exam_idx
    on public.gemini_usage_logs (exam_id, exam_subject_id);

alter table public.gemini_usage_logs enable row level security;
revoke all on public.gemini_usage_logs from anon, authenticated;
grant select, insert, update, delete on public.gemini_usage_logs to service_role;
grant usage, select on sequence public.gemini_usage_logs_id_seq to service_role;

create or replace function public.get_school_gemini_usage_summary(p_school_id bigint)
returns jsonb
language sql
stable
security invoker
set search_path = public
as $$
    select jsonb_build_object(
        'school_id', p_school_id,
        'total_analyses', count(*),
        'total_requests', coalesce(sum(request_count), 0),
        'total_retries', coalesce(sum(retry_count), 0),
        'input_tokens', coalesce(sum(prompt_tokens), 0),
        'output_tokens', coalesce(sum(coalesce(candidates_tokens,0) + coalesce(thoughts_tokens,0)), 0),
        'total_tokens', coalesce(sum(total_tokens), 0),
        'estimated_cost_usd', coalesce(sum(estimated_cost_usd), 0),
        'estimated_cost_tzs', case
            when bool_or(estimated_cost_tzs is null) then null
            else coalesce(sum(estimated_cost_tzs), 0)
        end,
        'unpriced_analyses', count(*) filter (where pricing_status <> 'estimated'),
        'last_analysis_at', max(created_at),
        'monthly', coalesce((
            select jsonb_agg(month_row order by month_row->>'month' desc)
            from (
                select jsonb_build_object(
                    'month', to_char(date_trunc('month', created_at), 'YYYY-MM'),
                    'analyses', count(*),
                    'tokens', coalesce(sum(total_tokens),0),
                    'cost_usd', coalesce(sum(estimated_cost_usd),0),
                    'cost_tzs', case when bool_or(estimated_cost_tzs is null) then null else coalesce(sum(estimated_cost_tzs),0) end
                ) as month_row
                from public.gemini_usage_logs
                where school_id = p_school_id
                group by date_trunc('month', created_at)
            ) monthly_rows
        ), '[]'::jsonb),
        'recent', coalesce((
            select jsonb_agg(recent_row order by recent_row->>'created_at' desc)
            from (
                select jsonb_build_object(
                    'id', id,
                    'exam_id', exam_id,
                    'exam_paper_id', exam_paper_id,
                    'model', model,
                    'prompt_tokens', prompt_tokens,
                    'candidates_tokens', candidates_tokens,
                    'thoughts_tokens', thoughts_tokens,
                    'total_tokens', total_tokens,
                    'estimated_cost_usd', estimated_cost_usd,
                    'estimated_cost_tzs', estimated_cost_tzs,
                    'pricing_status', pricing_status,
                    'created_at', created_at
                ) as recent_row
                from public.gemini_usage_logs
                where school_id = p_school_id
                order by created_at desc
                limit 20
            ) recent_rows
        ), '[]'::jsonb)
    )
    from public.gemini_usage_logs
    where school_id = p_school_id;
$$;

revoke all on function public.get_school_gemini_usage_summary(bigint) from public, anon, authenticated;
grant execute on function public.get_school_gemini_usage_summary(bigint) to service_role;
