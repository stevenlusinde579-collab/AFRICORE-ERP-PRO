-- Per-school audit trail for NewHope bulk SMS sent from the Communication Center.
create table if not exists public.school_sms_broadcast_history (
    id bigint generated by default as identity primary key,
    school_id bigint not null references public.schools(id) on delete cascade,
    sender_user_id uuid not null references auth.users(id) on delete restrict,
    audience text not null check (audience in ('staff', 'parents')),
    recipient_profile_id uuid references public.profiles(id) on delete set null,
    student_id bigint references public.students(id) on delete set null,
    recipient_name text not null,
    recipient_phone text not null,
    message text not null,
    provider text not null default 'NewHope SMS',
    provider_message_id text,
    status text not null default 'pending'
        check (status in ('pending', 'queued', 'sent', 'delivered', 'failed', 'skipped')),
    segments integer,
    cost numeric(12,4),
    error_message text,
    sent_at timestamptz,
    created_at timestamptz not null default now()
);

create index if not exists school_sms_broadcast_history_school_created_idx
    on public.school_sms_broadcast_history (school_id, created_at desc);

create index if not exists school_sms_broadcast_history_school_status_idx
    on public.school_sms_broadcast_history (school_id, status);

alter table public.school_sms_broadcast_history enable row level security;
revoke all on public.school_sms_broadcast_history from anon, authenticated;
grant select, insert, update on public.school_sms_broadcast_history to service_role;
