-- Private HR contracts and employee documents.
-- Storage paths are: <school_id>/<employee_id>/<random-file-name>
begin;

insert into storage.buckets (id,name,public,file_size_limit,allowed_mime_types)
values (
  'hr-employee-files',
  'hr-employee-files',
  false,
  20971520,
  array[
    'application/pdf',
    'application/msword',
    'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
    'image/jpeg',
    'image/png'
  ]
)
on conflict (id) do update
set public = false,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

create table if not exists public.hr_employee_documents (
  id bigint generated by default as identity primary key,
  employee_id bigint not null,
  school_id bigint not null references public.schools(id) on delete restrict,
  document_type text not null,
  document_title text not null,
  document_number text,
  issue_date date,
  expiry_date date,
  storage_path text not null unique,
  original_file_name text not null,
  mime_type text not null,
  file_size_bytes bigint not null check (file_size_bytes > 0 and file_size_bytes <= 20971520),
  notes text,
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id) on delete set null,
  constraint hr_employee_documents_employee_school_fkey
    foreign key (employee_id,school_id) references public.employees(id,school_id) on delete cascade,
  constraint hr_employee_documents_type_check
    check (document_type in ('national_id','passport','academic_certificate','professional_certificate','birth_certificate','medical_certificate','appointment_letter','confirmation_letter','promotion_letter','disciplinary_letter','termination_letter','cv','other')),
  constraint hr_employee_documents_dates_check
    check (expiry_date is null or issue_date is null or expiry_date >= issue_date)
);

create index if not exists hr_employee_documents_school_employee_idx
on public.hr_employee_documents(school_id,employee_id,created_at desc);

create table if not exists public.hr_employment_contracts (
  id bigint generated by default as identity primary key,
  employee_id bigint not null,
  school_id bigint not null references public.schools(id) on delete restrict,
  contract_number text not null,
  contract_type text not null,
  start_date date not null,
  end_date date,
  job_title text,
  department text,
  basic_salary numeric(14,2),
  salary_currency text not null default 'TZS',
  probation_end_date date,
  notice_period_days integer,
  status text not null default 'draft',
  storage_path text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid references auth.users(id) on delete set null,
  constraint hr_employment_contracts_employee_school_fkey
    foreign key (employee_id,school_id) references public.employees(id,school_id) on delete restrict,
  constraint hr_employment_contracts_number_school_unique unique (school_id,contract_number),
  constraint hr_employment_contracts_type_check
    check (contract_type in ('permanent','fixed_term','probation','part_time','temporary','consultancy','internship','other')),
  constraint hr_employment_contracts_status_check
    check (status in ('draft','pending_signature','active','expired','terminated','cancelled')),
  constraint hr_employment_contracts_dates_check
    check (end_date is null or end_date >= start_date),
  constraint hr_employment_contracts_salary_check
    check (basic_salary is null or basic_salary >= 0),
  constraint hr_employment_contracts_notice_check
    check (notice_period_days is null or notice_period_days >= 0),
  constraint hr_employment_contracts_storage_path_unique unique (storage_path)
);

create index if not exists hr_employment_contracts_school_employee_idx
on public.hr_employment_contracts(school_id,employee_id,start_date desc);

alter table public.hr_employee_documents enable row level security;
alter table public.hr_employment_contracts enable row level security;

drop policy if exists hr_employee_documents_hr_access on public.hr_employee_documents;
create policy hr_employee_documents_hr_access
on public.hr_employee_documents for all to authenticated
using (
  public.is_current_user_super_admin()
  or exists (
    select 1 from public.profile_roles pr
    join public.roles r on r.id=pr.role_id
    where pr.profile_id=(select auth.uid())
      and pr.is_active is true
      and pr.school_id=hr_employee_documents.school_id
      and lower(trim(r.role_name))='hr manager'
  )
)
with check (
  public.is_current_user_super_admin()
  or exists (
    select 1 from public.profile_roles pr
    join public.roles r on r.id=pr.role_id
    where pr.profile_id=(select auth.uid())
      and pr.is_active is true
      and pr.school_id=hr_employee_documents.school_id
      and lower(trim(r.role_name))='hr manager'
  )
);

drop policy if exists hr_employment_contracts_hr_access on public.hr_employment_contracts;
create policy hr_employment_contracts_hr_access
on public.hr_employment_contracts for all to authenticated
using (
