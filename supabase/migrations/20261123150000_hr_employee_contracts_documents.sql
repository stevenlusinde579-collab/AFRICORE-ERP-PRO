  or exists (
    select 1 from public.profile_roles pr
    join public.roles r on r.id=pr.role_id
    where pr.profile_id=(select auth.uid())
      and pr.is_active is true
      and pr.school_id=hr_employment_contracts.school_id
      and lower(trim(r.role_name))='hr manager'
  )
);

-- Storage access is limited to HR Manager / Super Admin and the employee's school.
drop policy if exists hr_employee_files_select_hr on storage.objects;
create policy hr_employee_files_select_hr
on storage.objects for select to authenticated
using (
  bucket_id='hr-employee-files'
  and (storage.foldername(name))[1] ~ '^[0-9]+$'
  and (storage.foldername(name))[2] ~ '^[0-9]+$'
  and exists (
    select 1 from public.employees e
    where e.id::text=(storage.foldername(name))[2]
      and e.school_id::text=(storage.foldername(name))[1]
  )
  and (
    public.is_current_user_super_admin()
    or exists (
      select 1 from public.profile_roles pr
      join public.roles r on r.id=pr.role_id
      where pr.profile_id=(select auth.uid())
        and pr.is_active is true
        and pr.school_id::text=(storage.foldername(name))[1]
        and lower(trim(r.role_name))='hr manager'
    )
  )
);

