-- HR owns staff signature registration; Secretary owns document signing workflows.
begin;

create table if not exists public.hr_staff_signatures (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools(id) on delete cascade,
  teacher_id bigint not null references public.teachers(id) on delete cascade,
  profile_id uuid not null references auth.users(id) on delete cascade,
  storage_path text not null,
  is_active boolean not null default true,
  registered_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (school_id, teacher_id)
);

create table if not exists public.document_signing_requests (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools(id) on delete cascade,
  title text not null,
  description text,
  document_path text not null,
  status text not null default 'pending' check (status in ('pending','in_progress','completed','cancelled')),
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.document_signing_recipients (
  id bigint generated by default as identity primary key,
  request_id bigint not null references public.document_signing_requests(id) on delete cascade,
  school_id bigint not null references public.schools(id) on delete cascade,
  teacher_id bigint not null references public.teachers(id) on delete cascade,
  profile_id uuid not null references auth.users(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending','signed','declined')),
  signature_id bigint references public.hr_staff_signatures(id) on delete set null,
  signed_at timestamptz,
  response_note text,
  created_at timestamptz not null default now(),
  unique (request_id, profile_id)
);

create index if not exists idx_hr_staff_signatures_school on public.hr_staff_signatures(school_id, is_active);
create index if not exists idx_signing_requests_school on public.document_signing_requests(school_id, created_at desc);
create index if not exists idx_signing_recipients_profile on public.document_signing_recipients(profile_id, status);
create index if not exists idx_signing_recipients_request on public.document_signing_recipients(request_id);

alter table public.hr_staff_signatures enable row level security;
alter table public.document_signing_requests enable row level security;
alter table public.document_signing_recipients enable row level security;

-- HR Manager can register/update signatures; each staff member can view own registration.
drop policy if exists hr_signatures_select on public.hr_staff_signatures;
create policy hr_signatures_select on public.hr_staff_signatures for select to authenticated
using (
  profile_id = auth.uid()
  or exists (
    select 1 from public.profile_roles pr join public.roles r on r.id=pr.role_id
    where pr.profile_id=auth.uid() and pr.school_id=hr_staff_signatures.school_id
      and pr.is_active is true and lower(trim(r.role_name)) in ('hr manager','headmaster','super admin','secretary')
  )
);
drop policy if exists hr_signatures_manage on public.hr_staff_signatures;
create policy hr_signatures_manage on public.hr_staff_signatures for all to authenticated
using (exists (
  select 1 from public.profile_roles pr join public.roles r on r.id=pr.role_id
  where pr.profile_id=auth.uid() and pr.school_id=hr_staff_signatures.school_id
    and pr.is_active is true and lower(trim(r.role_name)) in ('hr manager','headmaster','super admin')
))
with check (exists (
  select 1 from public.profile_roles pr join public.roles r on r.id=pr.role_id
  where pr.profile_id=auth.uid() and pr.school_id=hr_staff_signatures.school_id
    and pr.is_active is true and lower(trim(r.role_name)) in ('hr manager','headmaster','super admin')
));

-- Secretary/HR/Headmaster manage requests in their school.
drop policy if exists signing_requests_select on public.document_signing_requests;
create policy signing_requests_select on public.document_signing_requests for select to authenticated
using (
  exists (select 1 from public.profile_roles pr join public.roles r on r.id=pr.role_id
    where pr.profile_id=auth.uid() and pr.school_id=document_signing_requests.school_id
      and pr.is_active is true and lower(trim(r.role_name)) in ('secretary','hr manager','headmaster','super admin'))
  or exists (select 1 from public.document_signing_recipients dr
    where dr.request_id=document_signing_requests.id and dr.profile_id=auth.uid())
);
drop policy if exists signing_requests_insert on public.document_signing_requests;
create policy signing_requests_insert on public.document_signing_requests for insert to authenticated
with check (created_by=auth.uid() and exists (
  select 1 from public.profile_roles pr join public.roles r on r.id=pr.role_id
  where pr.profile_id=auth.uid() and pr.school_id=document_signing_requests.school_id
    and pr.is_active is true and lower(trim(r.role_name)) in ('secretary','hr manager','headmaster','super admin')
));
drop policy if exists signing_requests_update on public.document_signing_requests;
create policy signing_requests_update on public.document_signing_requests for update to authenticated
using (exists (
  select 1 from public.profile_roles pr join public.roles r on r.id=pr.role_id
  where pr.profile_id=auth.uid() and pr.school_id=document_signing_requests.school_id
    and pr.is_active is true and lower(trim(r.role_name)) in ('secretary','hr manager','headmaster','super admin')
))
with check (exists (
  select 1 from public.profile_roles pr join public.roles r on r.id=pr.role_id
  where pr.profile_id=auth.uid() and pr.school_id=document_signing_requests.school_id
    and pr.is_active is true and lower(trim(r.role_name)) in ('secretary','hr manager','headmaster','super admin')
));

-- Request managers can add recipients; a recipient can only update their own response.
drop policy if exists signing_recipients_select on public.document_signing_recipients;
create policy signing_recipients_select on public.document_signing_recipients for select to authenticated
using (
  profile_id=auth.uid()
  or exists (select 1 from public.profile_roles pr join public.roles r on r.id=pr.role_id
    where pr.profile_id=auth.uid() and pr.school_id=document_signing_recipients.school_id
      and pr.is_active is true and lower(trim(r.role_name)) in ('secretary','hr manager','headmaster','super admin'))
);
drop policy if exists signing_recipients_insert on public.document_signing_recipients;
create policy signing_recipients_insert on public.document_signing_recipients for insert to authenticated
with check (exists (
  select 1 from public.profile_roles pr join public.roles r on r.id=pr.role_id
  where pr.profile_id=auth.uid() and pr.school_id=document_signing_recipients.school_id
    and pr.is_active is true and lower(trim(r.role_name)) in ('secretary','hr manager','headmaster','super admin')
));
drop policy if exists signing_recipients_update on public.document_signing_recipients;
create policy signing_recipients_update on public.document_signing_recipients for update to authenticated
using (
  profile_id=auth.uid()
  or exists (select 1 from public.profile_roles pr join public.roles r on r.id=pr.role_id
    where pr.profile_id=auth.uid() and pr.school_id=document_signing_recipients.school_id
      and pr.is_active is true and lower(trim(r.role_name)) in ('secretary','hr manager','headmaster','super admin'))
)
with check (
  (profile_id=auth.uid() and status in ('signed','declined'))
  or exists (select 1 from public.profile_roles pr join public.roles r on r.id=pr.role_id
    where pr.profile_id=auth.uid() and pr.school_id=document_signing_recipients.school_id
      and pr.is_active is true and lower(trim(r.role_name)) in ('secretary','hr manager','headmaster','super admin'))
);

-- Private document bucket. Paths are school-id/request-id/filename.
insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
values ('school-signing-documents','school-signing-documents',false,15728640,array['application/pdf'])
on conflict (id) do update set public=false,file_size_limit=15728640,allowed_mime_types=array['application/pdf'];

insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
values ('hr-staff-signatures','hr-staff-signatures',false,2097152,array['image/png','image/jpeg'])
on conflict (id) do update set public=false,file_size_limit=2097152,allowed_mime_types=array['image/png','image/jpeg'];

drop policy if exists signing_docs_read on storage.objects;
create policy signing_docs_read on storage.objects for select to authenticated
using (bucket_id='school-signing-documents' and exists (
  select 1 from public.profile_roles pr join public.roles r on r.id=pr.role_id
  where pr.profile_id=auth.uid() and pr.school_id=(storage.foldername(name))[1]::bigint
    and pr.is_active is true and lower(trim(r.role_name)) in ('secretary','hr manager','headmaster','super admin')
));
drop policy if exists signing_docs_insert on storage.objects;
create policy signing_docs_insert on storage.objects for insert to authenticated
with check (bucket_id='school-signing-documents' and exists (
  select 1 from public.profile_roles pr join public.roles r on r.id=pr.role_id
  where pr.profile_id=auth.uid() and pr.school_id=(storage.foldername(name))[1]::bigint
    and pr.is_active is true and lower(trim(r.role_name)) in ('secretary','hr manager','headmaster','super admin')
));

drop policy if exists hr_signature_files_read on storage.objects;
create policy hr_signature_files_read on storage.objects for select to authenticated
using (bucket_id='hr-staff-signatures' and exists (
  select 1 from public.profile_roles pr join public.roles r on r.id=pr.role_id
  where pr.profile_id=auth.uid() and pr.school_id=(storage.foldername(name))[1]::bigint
    and pr.is_active is true and lower(trim(r.role_name)) in ('hr manager','headmaster','super admin')
));
drop policy if exists hr_signature_files_insert on storage.objects;
create policy hr_signature_files_insert on storage.objects for insert to authenticated
with check (bucket_id='hr-staff-signatures' and exists (
  select 1 from public.profile_roles pr join public.roles r on r.id=pr.role_id
  where pr.profile_id=auth.uid() and pr.school_id=(storage.foldername(name))[1]::bigint
    and pr.is_active is true and lower(trim(r.role_name)) in ('hr manager','headmaster','super admin')
));

commit;
