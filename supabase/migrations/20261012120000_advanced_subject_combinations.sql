-- Advanced-level subject combinations.
-- Safe additive migration: existing subjects, students, marks and exams are preserved.

create table if not exists public.subject_combinations (
  id bigint generated by default as identity primary key,
  school_id bigint null references public.schools(id) on delete cascade,
  combination_code text not null,
  combination_name text not null,
  level_scope text not null default 'Both'
    check (level_scope in ('Form 5', 'Form 6', 'Both')),
  suggested_subjects text[] not null default '{}',
  description text null,
  is_system_default boolean not null default false,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create unique index if not exists subject_combinations_school_code_uidx
  on public.subject_combinations (coalesce(school_id, 0), upper(trim(combination_code)));

create table if not exists public.combination_subjects (
  id bigint generated by default as identity primary key,
  combination_id bigint not null references public.subject_combinations(id) on delete cascade,
  subject_id bigint not null references public.subjects(id) on delete restrict,
  created_at timestamptz not null default now(),
  unique (combination_id, subject_id)
);

alter table public.students
  add column if not exists combination_id bigint null
  references public.subject_combinations(id) on delete restrict;

alter table public.subject_combinations enable row level security;
alter table public.combination_subjects enable row level security;

drop policy if exists "Read system and own school combinations" on public.subject_combinations;
create policy "Read system and own school combinations"
  on public.subject_combinations for select to authenticated
  using (
    school_id is null
    or school_id = (select p.school_id from public.profiles p where p.id = auth.uid())
  );

drop policy if exists "Create own school combinations" on public.subject_combinations;
create policy "Create own school combinations"
  on public.subject_combinations for insert to authenticated
  with check (
    school_id is not null
    and school_id = (select p.school_id from public.profiles p where p.id = auth.uid())
    and is_system_default = false
  );

drop policy if exists "Update own school combinations" on public.subject_combinations;
create policy "Update own school combinations"
  on public.subject_combinations for update to authenticated
  using (
    school_id is not null
    and school_id = (select p.school_id from public.profiles p where p.id = auth.uid())
    and is_system_default = false
  )
  with check (
    school_id is not null
    and school_id = (select p.school_id from public.profiles p where p.id = auth.uid())
    and is_system_default = false
  );

drop policy if exists "Delete own school combinations" on public.subject_combinations;
create policy "Delete own school combinations"
  on public.subject_combinations for delete to authenticated
  using (
    school_id is not null
    and school_id = (select p.school_id from public.profiles p where p.id = auth.uid())
    and is_system_default = false
  );

drop policy if exists "Read subjects for visible combinations" on public.combination_subjects;
create policy "Read subjects for visible combinations"
  on public.combination_subjects for select to authenticated
  using (
    exists (
      select 1 from public.subject_combinations c
      where c.id = combination_id
        and (
          c.school_id is null
          or c.school_id = (select p.school_id from public.profiles p where p.id = auth.uid())
        )
    )
  );

drop policy if exists "Manage subjects for own combinations" on public.combination_subjects;
create policy "Manage subjects for own combinations"
  on public.combination_subjects for all to authenticated
  using (
    exists (
      select 1 from public.subject_combinations c
      where c.id = combination_id
        and c.school_id is not null
        and c.school_id = (select p.school_id from public.profiles p where p.id = auth.uid())
        and c.is_system_default = false
    )
  )
  with check (
    exists (
      select 1 from public.subject_combinations c
      where c.id = combination_id
        and c.school_id is not null
        and c.school_id = (select p.school_id from public.profiles p where p.id = auth.uid())
        and c.is_system_default = false
    )
  );

