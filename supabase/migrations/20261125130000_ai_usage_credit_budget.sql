-- Record Gemini prepaid-credit purchases and expose a SuperAdmin-only balance summary.
-- This tracks credits the administrator records as purchased; it does not connect to Google's billing account.

create table if not exists public.gemini_ai_credit_purchases (
    id bigint generated by default as identity primary key,
    amount_usd numeric(18,6) not null check (amount_usd > 0),
    exchange_rate_tzs numeric(18,6) check (exchange_rate_tzs is null or exchange_rate_tzs > 0),
    paid_amount_tzs numeric(18,2) check (paid_amount_tzs is null or paid_amount_tzs >= 0),
    payment_reference text,
    admin_note text,
    purchased_at timestamptz not null default now(),
    recorded_by uuid references public.profiles(id) on delete set null,
    created_at timestamptz not null default now()
);

create index if not exists gemini_ai_credit_purchases_purchased_at_idx
    on public.gemini_ai_credit_purchases (purchased_at desc);

alter table public.gemini_ai_credit_purchases enable row level security;
revoke all on public.gemini_ai_credit_purchases from anon, authenticated;
grant select, insert on public.gemini_ai_credit_purchases to service_role;
grant usage, select on sequence public.gemini_ai_credit_purchases_id_seq to service_role;

create or replace function public.get_gemini_ai_credit_budget()
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
with purchases as (
    select
        coalesce(sum(amount_usd), 0)::numeric as total_purchased_usd,
        coalesce(sum(paid_amount_tzs), 0)::numeric as total_paid_tzs,
        count(*)::integer as purchase_count
    from public.gemini_ai_credit_purchases
),
usage as (
    select
        coalesce(sum(estimated_cost_usd), 0)::numeric as total_spent_usd,
        count(*) filter (where pricing_status <> 'estimated' or estimated_cost_usd is null)::integer as unpriced_analyses,
        count(*)::integer as analyses_recorded
    from public.gemini_usage_logs
),
recent as (
    select coalesce(jsonb_agg(to_jsonb(q) order by q.purchased_at desc), '[]'::jsonb) as items
    from (
        select id, amount_usd, exchange_rate_tzs, paid_amount_tzs,
               payment_reference, admin_note, purchased_at
        from public.gemini_ai_credit_purchases
        order by purchased_at desc
        limit 30
    ) q
)
select jsonb_build_object(
    'total_purchased_usd', p.total_purchased_usd,
    'total_paid_tzs', p.total_paid_tzs,
    'purchase_count', p.purchase_count,
    'total_spent_usd', u.total_spent_usd,
    'remaining_usd', p.total_purchased_usd - u.total_spent_usd,
    'unpriced_analyses', u.unpriced_analyses,
    'analyses_recorded', u.analyses_recorded,
    'balance_is_estimate', u.unpriced_analyses > 0,
    'purchases', r.items
)
from purchases p cross join usage u cross join recent r;
$$;

create or replace function public.record_gemini_ai_credit_purchase(
    p_amount_usd numeric,
    p_exchange_rate_tzs numeric default null,
    p_paid_amount_tzs numeric default null,
    p_payment_reference text default null,
    p_admin_note text default null,
    p_recorded_by uuid default null
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_id bigint;
begin
    if p_amount_usd is null or p_amount_usd <= 0
       or (p_exchange_rate_tzs is not null and p_exchange_rate_tzs <= 0)
       or (p_paid_amount_tzs is not null and p_paid_amount_tzs < 0) then
        raise exception 'Enter a valid positive credit amount and valid optional payment details';
    end if;

    insert into public.gemini_ai_credit_purchases
        (amount_usd, exchange_rate_tzs, paid_amount_tzs, payment_reference, admin_note, recorded_by)
    values
        (p_amount_usd, p_exchange_rate_tzs, p_paid_amount_tzs,
         nullif(left(trim(coalesce(p_payment_reference,'')),120),''),
         nullif(left(trim(coalesce(p_admin_note,'')),500),''),
         p_recorded_by)
    returning id into v_id;

    return v_id;
end;
$$;

revoke all on function public.get_gemini_ai_credit_budget() from public, anon, authenticated;
revoke all on function public.record_gemini_ai_credit_purchase(numeric,numeric,numeric,text,text,uuid) from public, anon, authenticated;
grant execute on function public.get_gemini_ai_credit_budget() to service_role;
grant execute on function public.record_gemini_ai_credit_purchase(numeric,numeric,numeric,text,text,uuid) to service_role;
