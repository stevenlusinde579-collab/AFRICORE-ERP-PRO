-- AfriCore ERP PRO: tenant-scoped stock management
-- This migration is additive. It does not alter existing finance supplier/bill/payment records.

create table if not exists public.stock_categories (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools(id) on delete cascade,
  name text not null,
  category_type text not null default 'general'
    check (category_type in ('food','uniform','stationery','equipment','cleaning','sports','general')),
  description text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id),
  unique (school_id, name)
);

create table if not exists public.stock_locations (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools(id) on delete cascade,
  name text not null,
  description text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id),
  unique (school_id, name)
);

create table if not exists public.stock_items (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools(id) on delete cascade,
  category_id bigint references public.stock_categories(id) on delete set null,
  sku text,
  item_name text not null,
  description text,
  unit_of_measure text not null default 'pcs',
  reorder_level numeric(14,3) not null default 0 check (reorder_level >= 0),
  cost_price numeric(14,2) not null default 0 check (cost_price >= 0),
  selling_price numeric(14,2) not null default 0 check (selling_price >= 0),
  is_for_sale boolean not null default false,
  track_expiry boolean not null default false,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id),
  unique (school_id, sku)
);

create table if not exists public.stock_balances (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools(id) on delete cascade,
  item_id bigint not null references public.stock_items(id) on delete cascade,
  location_id bigint not null references public.stock_locations(id) on delete restrict,
  quantity_on_hand numeric(14,3) not null default 0 check (quantity_on_hand >= 0),
  updated_at timestamptz not null default now(),
  unique (school_id, item_id, location_id)
);

create table if not exists public.stock_movements (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools(id) on delete cascade,
  item_id bigint not null references public.stock_items(id) on delete restrict,
  location_id bigint not null references public.stock_locations(id) on delete restrict,
  movement_type text not null check (movement_type in (
    'opening','receive','return','issue','sale','damaged','expired',
    'adjustment_in','adjustment_out','transfer_in','transfer_out'
  )),
  quantity numeric(14,3) not null check (quantity > 0),
  unit_cost numeric(14,2) not null default 0 check (unit_cost >= 0),
  reference_number text,
  notes text,
  movement_date date not null default current_date,
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id)
);

create table if not exists public.stock_purchase_orders (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools(id) on delete cascade,
  supplier_id bigint references finance.suppliers(id) on delete set null,
  order_number text not null,
  order_date date not null default current_date,
  expected_delivery_date date,
  status text not null default 'draft'
    check (status in ('draft','submitted','approved','partially_received','received','cancelled')),
  notes text,
  total_amount numeric(14,2) not null default 0 check (total_amount >= 0),
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id),
  approved_at timestamptz,
  approved_by uuid references auth.users(id),
  unique (school_id, order_number)
);

create table if not exists public.stock_purchase_order_items (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools(id) on delete cascade,
  purchase_order_id bigint not null references public.stock_purchase_orders(id) on delete cascade,
  item_id bigint not null references public.stock_items(id) on delete restrict,
  quantity_ordered numeric(14,3) not null check (quantity_ordered > 0),
  quantity_received numeric(14,3) not null default 0
    check (quantity_received >= 0 and quantity_received <= quantity_ordered),
  unit_cost numeric(14,2) not null default 0 check (unit_cost >= 0),
  line_total numeric(14,2) generated always as (round(quantity_ordered * unit_cost, 2)) stored
);

create table if not exists public.stock_student_orders (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools(id) on delete cascade,
  student_id bigint not null references public.students(id) on delete restrict,
  order_number text not null,
  order_date date not null default current_date,
  status text not null default 'pending'
    check (status in ('pending','partially_fulfilled','fulfilled','cancelled')),
  payment_status text not null default 'unpaid'
    check (payment_status in ('unpaid','partially_paid','paid')),
  total_amount numeric(14,2) not null default 0 check (total_amount >= 0),
  notes text,
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id),
  unique (school_id, order_number)
);

create table if not exists public.stock_student_order_items (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools(id) on delete cascade,
  student_order_id bigint not null references public.stock_student_orders(id) on delete cascade,
  item_id bigint not null references public.stock_items(id) on delete restrict,
  quantity_ordered numeric(14,3) not null check (quantity_ordered > 0),
  quantity_issued numeric(14,3) not null default 0
    check (quantity_issued >= 0 and quantity_issued <= quantity_ordered),
  unit_price numeric(14,2) not null default 0 check (unit_price >= 0)
);

create index if not exists idx_stock_items_school_category on public.stock_items(school_id, category_id);
create index if not exists idx_stock_balances_school_item on public.stock_balances(school_id, item_id);
create index if not exists idx_stock_movements_school_date on public.stock_movements(school_id, movement_date desc);
create index if not exists idx_stock_orders_school_status on public.stock_purchase_orders(school_id, status);
create index if not exists idx_stock_student_orders_school_date on public.stock_student_orders(school_id, order_date desc);

-- Every stock movement updates the running balance in the same database transaction.
create or replace function public.apply_stock_movement_to_balance()
returns trigger
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_delta numeric(14,3);
  v_item_school bigint;
  v_location_school bigint;
begin
  select school_id into v_item_school from public.stock_items where id = new.item_id;
  select school_id into v_location_school from public.stock_locations where id = new.location_id;

  if v_item_school is distinct from new.school_id
     or v_location_school is distinct from new.school_id then
    raise exception 'Stock item and location must belong to the selected school.';
  end if;

  v_delta := case
    when new.movement_type in ('opening','receive','return','adjustment_in','transfer_in') then new.quantity
    else -new.quantity
  end;

  insert into public.stock_balances (school_id, item_id, location_id, quantity_on_hand, updated_at)
  values (new.school_id, new.item_id, new.location_id, v_delta, now())
  on conflict (school_id, item_id, location_id)
  do update set
    quantity_on_hand = public.stock_balances.quantity_on_hand + excluded.quantity_on_hand,
    updated_at = now()
  where public.stock_balances.quantity_on_hand + excluded.quantity_on_hand >= 0;

  if not found then
    raise exception 'Insufficient stock. This movement would make the balance negative.';
  end if;

  return new;
end;
$$;

drop trigger if exists trg_apply_stock_movement_to_balance on public.stock_movements;
create trigger trg_apply_stock_movement_to_balance
after insert on public.stock_movements
for each row execute function public.apply_stock_movement_to_balance();

-- Validate supplier and order-line ownership across tenant boundaries.
create or replace function public.validate_stock_purchase_order_tenant()
returns trigger
language plpgsql
security invoker
set search_path = public, finance, pg_temp
as $$
begin
  if new.supplier_id is not null and not exists (
    select 1 from finance.suppliers s
    where s.id = new.supplier_id and s.school_id = new.school_id
  ) then
    raise exception 'Supplier must belong to the same school.';
  end if;
  return new;
end;
$$;

drop trigger if exists trg_validate_stock_purchase_order_tenant on public.stock_purchase_orders;
create trigger trg_validate_stock_purchase_order_tenant
before insert or update on public.stock_purchase_orders
for each row execute function public.validate_stock_purchase_order_tenant();

create or replace function public.validate_stock_order_item_tenant()
returns trigger
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
begin
  if not exists (
    select 1 from public.stock_items i
    where i.id = new.item_id and i.school_id = new.school_id
  ) then
    raise exception 'Stock item must belong to the same school.';
  end if;
  if tg_table_name = 'stock_purchase_order_items' and not exists (
    select 1 from public.stock_purchase_orders o
    where o.id = new.purchase_order_id and o.school_id = new.school_id
  ) then
    raise exception 'Purchase order must belong to the same school.';
  end if;
  if tg_table_name = 'stock_student_order_items' and not exists (
    select 1 from public.stock_student_orders o
    where o.id = new.student_order_id and o.school_id = new.school_id
  ) then
    raise exception 'Student order must belong to the same school.';
  end if;
  return new;
end;
$$;

drop trigger if exists trg_validate_stock_po_item_tenant on public.stock_purchase_order_items;
create trigger trg_validate_stock_po_item_tenant
before insert or update on public.stock_purchase_order_items
for each row execute function public.validate_stock_order_item_tenant();

