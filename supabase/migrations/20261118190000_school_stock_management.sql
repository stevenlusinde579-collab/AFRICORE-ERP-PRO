-- App-level permissions are keyed by role name rather than hard-coded role IDs.
insert into public.permissions (permission_name, module, description, is_active)
values
  ('view_stock','stock','View school stock, balances, orders and reports',true),
  ('manage_stock','stock','Create and maintain stock items, categories and stock records',true),
  ('receive_stock','stock','Receive purchased goods into school stores',true),
  ('issue_stock','stock','Issue goods to departments and record consumption',true),
  ('approve_stock_orders','stock','Approve or reject stock purchase orders',true)
on conflict (permission_name) do update
set module = excluded.module, description = excluded.description, is_active = true;

insert into public.role_permissions (role_id, permission_id)
select r.id, p.id
from public.roles r
cross join public.permissions p
where lower(trim(r.role_name)) in ('headmaster','accountant','super admin')
  and p.permission_name in ('view_stock','manage_stock')
on conflict do nothing;

insert into public.role_permissions (role_id, permission_id)
