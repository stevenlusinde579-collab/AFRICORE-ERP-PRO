-- Every stock movement updates the running balance in the same database transaction.
create or replace function public.apply_stock_movement_to_balance()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_delta numeric(14,3);
  v_item_school bigint;
  v_location_school bigint;
begin
  if not public.is_current_user_super_admin() then
    if auth.uid() is null or new.school_id is distinct from public.get_current_user_school_id()
       or not exists (
         select 1 from public.profile_roles pr join public.roles r on r.id = pr.role_id
         where pr.profile_id = auth.uid() and pr.school_id = new.school_id and pr.is_active is true
           and lower(trim(r.role_name)) in ('headmaster','accountant')
       ) then
      raise exception 'You are not authorised to post stock movements for this school.';
    end if;
  end if;

  select school_id into v_item_school from public.stock_items where id = new.item_id;
  select school_id into v_location_school from public.stock_locations where id = new.location_id;

  if v_item_school is distinct from new.school_id
     or v_location_school is distinct from new.school_id then
    raise exception 'Stock item and location must belong to the selected school.';
  end if;

  v_delta := case
    when new.movement_type in ('opening','receive','return','adjustment_in','transfer_in') then new.quantity
    else -new.quantity
  end;

  insert into public.stock_balances (school_id, item_id, location_id, quantity_on_hand, updated_at)
  values (new.school_id, new.item_id, new.location_id, v_delta, now())
  on conflict (school_id, item_id, location_id)
  do update set
    quantity_on_hand = public.stock_balances.quantity_on_hand + excluded.quantity_on_hand,
    updated_at = now()
  where public.stock_balances.quantity_on_hand + excluded.quantity_on_hand >= 0;

  if not found then
    raise exception 'Insufficient stock. This movement would make the balance negative.';
  end if;

  return new;
end;
$$;

drop trigger if exists trg_apply_stock_movement_to_balance on public.stock_movements;
create trigger trg_apply_stock_movement_to_balance
after insert on public.stock_movements
for each row execute function public.apply_stock_movement_to_balance();

-- Validate supplier and order-line ownership across tenant boundaries.
create or replace function public.validate_stock_purchase_order_tenant()
returns trigger
language plpgsql
security invoker
set search_path = public, finance, pg_temp
as $$
begin
  if new.supplier_id is not null and not exists (
    select 1 from finance.suppliers s
    where s.id = new.supplier_id and s.school_id = new.school_id
  ) then
    raise exception 'Supplier must belong to the same school.';
  end if;
  return new;
end;
$$;

drop trigger if exists trg_validate_stock_purchase_order_tenant on public.stock_purchase_orders;
create trigger trg_validate_stock_purchase_order_tenant
before insert or update on public.stock_purchase_orders
for each row execute function public.validate_stock_purchase_order_tenant();

