-- Auditable payment records for parent/student stock orders.
-- Payments are separate ledger rows; stock is changed only by fulfilment RPCs.

create table if not exists public.stock_student_order_payments (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools(id) on delete cascade,
  student_order_id bigint not null references public.stock_student_orders(id) on delete cascade,
  amount numeric(14,2) not null check (amount > 0),
  payment_method text not null check (payment_method in ('cash','bank_transfer','mobile_money','cheque','other')),
  payment_reference text,
  payment_date date not null default current_date,
  notes text,
  received_by uuid references auth.users(id),
  created_at timestamptz not null default now()
);

create index if not exists idx_stock_student_order_payments_order
  on public.stock_student_order_payments(school_id, student_order_id, payment_date desc);

alter table public.stock_student_order_payments enable row level security;
drop policy if exists stock_student_order_payments_select on public.stock_student_order_payments;
create policy stock_student_order_payments_select
  on public.stock_student_order_payments
  for select to authenticated
  using (
    public.is_current_user_super_admin()
    or (
      school_id = public.get_current_user_school_id()
      and exists (
        select 1 from public.profile_roles pr
        join public.roles r on r.id = pr.role_id
        where pr.profile_id = auth.uid()
          and pr.school_id = stock_student_order_payments.school_id
          and pr.is_active is true
          and lower(trim(r.role_name)) in ('headmaster','accountant')
      )
    )
  );

grant select on public.stock_student_order_payments to authenticated;
grant usage, select on sequence public.stock_student_order_payments_id_seq to authenticated;
revoke insert, update, delete on public.stock_student_order_payments from anon, authenticated;

create or replace function public.record_stock_student_order_payment(
  p_order_id bigint,
  p_amount numeric,
  p_payment_method text,
  p_payment_date date default current_date,
  p_payment_reference text default null,
  p_notes text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_order public.stock_student_orders%rowtype;
  v_paid numeric(14,2);
  v_balance numeric(14,2);
  v_status text;
  v_payment_id bigint;
begin
  if auth.uid() is null then
    raise exception 'Authentication is required.';
  end if;

  select * into v_order
  from public.stock_student_orders
  where id = p_order_id
  for update;

  if not found then
    raise exception 'Student order was not found.';
  end if;

  if not public.is_current_user_super_admin() and (
    v_order.school_id <> public.get_current_user_school_id()
    or not exists (
      select 1 from public.profile_roles pr
      join public.roles r on r.id = pr.role_id
      where pr.profile_id = auth.uid()
        and pr.school_id = v_order.school_id
        and pr.is_active is true
        and lower(trim(r.role_name)) in ('headmaster','accountant')
    )
  ) then
    raise exception 'Only the school Headmaster or Accountant may record order payments.';
  end if;

  if v_order.status = 'cancelled' then
    raise exception 'Payments cannot be recorded against a cancelled order.';
  end if;

  if p_amount is null or p_amount <= 0 then
    raise exception 'Payment amount must be greater than zero.';
  end if;

  if p_payment_method not in ('cash','bank_transfer','mobile_money','cheque','other') then
    raise exception 'Select a valid payment method.';
  end if;

  select coalesce(sum(amount), 0) into v_paid
  from public.stock_student_order_payments
  where student_order_id = v_order.id
    and school_id = v_order.school_id;

  v_balance := greatest(0, v_order.total_amount - v_paid);
  if p_amount > v_balance then
    raise exception 'Payment exceeds the outstanding order balance of %.', v_balance;
  end if;

  insert into public.stock_student_order_payments (
    school_id, student_order_id, amount, payment_method,
    payment_reference, payment_date, notes, received_by
  ) values (
    v_order.school_id, v_order.id, p_amount, p_payment_method,
    nullif(left(trim(coalesce(p_payment_reference, '')), 120), ''),
    coalesce(p_payment_date, current_date),
    nullif(left(trim(coalesce(p_notes, '')), 1000), ''),
    auth.uid()
  ) returning id into v_payment_id;

  v_paid := v_paid + p_amount;
  v_status := case when v_paid >= v_order.total_amount then 'paid'
                   when v_paid > 0 then 'partially_paid'
                   else 'unpaid' end;

  update public.stock_student_orders
  set payment_status = v_status
  where id = v_order.id and school_id = v_order.school_id;

  return jsonb_build_object(
    'success', true,
    'payment_id', v_payment_id,
    'amount_paid', v_paid,
    'balance', greatest(0, v_order.total_amount - v_paid),
    'payment_status', v_status
  );
end;
$$;

revoke all on function public.record_stock_student_order_payment(bigint,numeric,text,date,text,text) from public, anon;
grant execute on function public.record_stock_student_order_payment(bigint,numeric,text,date,text,text) to authenticated;
