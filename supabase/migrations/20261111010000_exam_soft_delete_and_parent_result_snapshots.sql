-- Exam soft deletion, recovery, and durable Parent Portal result copies.
-- Applied to the production project before this source migration was committed.
alter table public.exams
  add column if not exists deleted_at timestamptz,
  add column if not exists deleted_by uuid,
  add column if not exists delete_reason text;

create index if not exists exams_active_school_year_idx
  on public.exams (school_id, academic_year_id, created_at desc)
  where deleted_at is null;

create index if not exists exams_deleted_school_year_idx
  on public.exams (school_id, academic_year_id, deleted_at desc)
  where deleted_at is not null;

create table if not exists public.parent_portal_result_snapshots (
  id bigint generated by default as identity primary key,
  school_id bigint not null,
  exam_id bigint not null,
  student_id bigint not null,
  exam_snapshot jsonb not null,
  result_snapshot jsonb,
  marks_snapshot jsonb not null default '[]'::jsonb,
  subjects_snapshot jsonb not null default '[]'::jsonb,
  published_at timestamptz not null default now(),
  published_by uuid,
  created_at timestamptz not null default now(),
  constraint parent_portal_result_snapshots_unique unique (school_id, exam_id, student_id)
);

create index if not exists parent_portal_result_snapshots_student_idx
  on public.parent_portal_result_snapshots (school_id, student_id, published_at desc);

create index if not exists parent_portal_result_snapshots_exam_idx
  on public.parent_portal_result_snapshots (school_id, exam_id);

alter table public.parent_portal_result_snapshots enable row level security;

comment on table public.parent_portal_result_snapshots is
  'Immutable per-student Parent Portal result copies. Deliberately has no foreign keys to exams or students so published results survive permanent deletion of source records.';
