-- HR Manager role, off-day planning, leave and USB biometric attendance.
-- This migration is committed to a feature branch only; it is NOT applied to production.

insert into public.roles (role_name, description)
values ('HR Manager', 'Manages school staff records, off-days, leave and attendance.')
on conflict (role_name) do update
set description = excluded.description;

insert into public.permissions (permission_name, module, module_name, action_name, description, is_active)
values
  ('view_hr', 'hr', 'Human Resources', 'view', 'View HR dashboard and staff HR records.', true),
  ('manage_hr', 'hr', 'Human Resources', 'manage', 'Manage HR settings and staff HR workflows.', true),
  ('manage_hr_offdays', 'hr', 'Off Day Management', 'manage', 'Set annual off-day entitlements and staggered staff rosters.', true),
  ('manage_hr_attendance', 'hr', 'Attendance', 'manage', 'Manage staff attendance and biometric device connections.', true),
  ('manage_hr_leave', 'hr', 'Leave Management', 'manage', 'Review and manage staff leave requests.', true),
  ('send_messages', 'communication', 'Communication', 'send', 'Send school communication messages.', true)
on conflict (permission_name) do update
set module = excluded.module,
    module_name = excluded.module_name,
    action_name = excluded.action_name,
    description = excluded.description,
    is_active = true;

insert into public.role_permissions (role_id, permission_id)
select r.id, p.id
from public.roles r
cross join public.permissions p
where r.role_name in ('HR Manager', 'Headmaster')
  and p.permission_name in ('view_hr', 'manage_hr', 'manage_hr_offdays', 'manage_hr_attendance', 'manage_hr_leave', 'view_staff', 'create_staff', 'edit_staff', 'send_messages')
on conflict do nothing;

create table if not exists public.hr_offday_policies (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools(id) on delete cascade,
  policy_name text not null default 'Annual Staff Off-Day Policy',
  annual_entitlement_days numeric(6,2) not null default 0 check (annual_entitlement_days >= 0),
  minimum_staff_on_duty_percent numeric(5,2) not null default 70 check (minimum_staff_on_duty_percent between 0 and 100),
  effective_from date not null default current_date,
  is_active boolean not null default true,
  created_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now(),
  unique (school_id, policy_name)
);

create table if not exists public.hr_offday_entitlements (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools(id) on delete cascade,
  employee_id bigint not null,
  entitlement_year integer not null,
  entitled_days numeric(6,2) not null check (entitled_days >= 0),
  created_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now(),
  unique (school_id, employee_id, entitlement_year)
);

create table if not exists public.hr_offday_rosters (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools(id) on delete cascade,
  employee_id bigint not null,
  off_date date not null,
  status text not null default 'planned' check (status in ('planned','taken','cancelled')),
  notes text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  unique (employee_id, off_date)
);

create table if not exists public.hr_leave_requests (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools(id) on delete cascade,
  employee_id bigint not null,
  leave_type text not null,
  start_date date not null,
  end_date date not null,
  days_requested numeric(6,2) not null check (days_requested > 0),
  reason text,
  status text not null default 'pending' check (status in ('pending','approved','rejected','cancelled')),
  reviewed_by uuid references auth.users(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  check (end_date >= start_date)
);

create table if not exists public.hr_biometric_devices (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools(id) on delete cascade,
  device_name text not null,
  device_model text,
  manufacturer text,
  connection_type text not null default 'USB' check (connection_type in ('USB','NETWORK','OTHER')),
  bridge_status text not null default 'not_connected' check (bridge_status in ('not_connected','connected','error','disabled')),
  device_serial_number text,
  last_seen_at timestamptz,
  settings jsonb not null default '{}'::jsonb,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.hr_attendance_events (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools(id) on delete cascade,
  employee_id bigint not null,
  device_id bigint,
  event_type text not null check (event_type in ('check_in','check_out')),
  event_source text not null default 'manual' check (event_source in ('manual','usb_biometric','import')),
  occurred_at timestamptz not null default now(),
  external_event_id text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create unique index if not exists hr_attendance_external_event_uidx
on public.hr_attendance_events (school_id, external_event_id)
where external_event_id is not null;

create index if not exists hr_offday_rosters_school_date_idx
on public.hr_offday_rosters (school_id, off_date, status);

create index if not exists hr_attendance_events_school_time_idx
on public.hr_attendance_events (school_id, occurred_at desc);

create index if not exists hr_leave_requests_school_status_idx
on public.hr_leave_requests (school_id, status, start_date);

do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'hr_offday_policies',
    'hr_offday_entitlements',
    'hr_offday_rosters',
    'hr_leave_requests',
    'hr_biometric_devices',
    'hr_attendance_events'
  ]
  loop
    execute format('alter table public.%I enable row level security', table_name);
    execute format('drop policy if exists hr_school_scope on public.%I', table_name);
    execute format(
      'create policy hr_school_scope on public.%I for all to authenticated using (
        public.is_current_user_super_admin()
        or school_id in (
          select pr.school_id
          from public.profile_roles pr
          join public.roles r on r.id = pr.role_id
          where pr.profile_id = auth.uid()
            and pr.is_active is true
            and pr.school_id is not null
            and lower(trim(r.role_name)) in (''hr manager'', ''headmaster'')
        )
      ) with check (
        public.is_current_user_super_admin()
        or school_id in (
          select pr.school_id
          from public.profile_roles pr
          join public.roles r on r.id = pr.role_id
          where pr.profile_id = auth.uid()
            and pr.is_active is true
            and pr.school_id is not null
            and lower(trim(r.role_name)) in (''hr manager'', ''headmaster'')
        )
      )',
      table_name
    );
  end loop;
end $$;

